local function takeoff(p, t)
  local r = p.r
  cur = { key = r.key, ids = r.ids, names = r.names, n = r.n, known = r.known, est = p.est, mine = p.mine,
          fast = p.fast, dest = shortName(r.names[r.n]), gt = t, st = serverNow(), learn = true, hidden = false,
          who = who() }
  lastUp = t
  settings().flightNow = cur
  FL.takeoffs = FL.takeoffs + 1
  boatsAgain(false)
  showBar()
end

-- Keep v (rounded to 1/per) as the newest of a route's last few.
local function keep(t, k, v, per)
  local l = list(t[k])
  l[#l + 1] = floor(v * per + 0.5) / per
  while #l > SAMPLES do tremove(l, 1) end
  t[k] = l
end

-- Did the flight end where it was going? Unknown (no position) counts as yes.
local function arrived(f)
  local id = f.known and plain(f.ids[f.n])
  local node = id and NODES[id]
  local x, y = position()
  if not node or not x then return true end
  local dx, dy = x - node[2], y - node[3]
  return sqrt(dx * dx + dy * dy) <= NEAR
end

local function land(t)
  local f = cur
  cur = nil
  settings().flightNow = nil
  hideBar()
  if f then boatsAgain(true) end
  if not f or not t then return end
  local dur = t - f.gt
  FL.lastFlight = { key = f.key, seconds = dur, learned = false }
  if not (f.learn and dur > 5 and arrived(f)) then return end
  -- Which speed and which kind of join it was: the data's time nearest to it.
  local isFast, ref, model = f.fast, nil, nil
  if f.known then
    for _, ff in ipairs({ false, true }) do
      for _, m in ipairs({ "short", "full" }) do
        local d = dataTime(f.ids, f.n, ff, m)
        if d and (not ref or abs(dur - d) < abs(dur - ref)) then isFast, ref, model = ff, d, m end
      end
    end
  end
  if ref then
    if abs(dur - ref) > max(LEARN_MIN, ref * LEARN_TOL) then return end   -- not a plain flight: not kept
  elseif dur > 1800 then
    return
  end
  local g = f.who or who()
  keep(sub("flightTimes"), timesKey(f.key, isFast), dur, 10)
  if ref then
    keep(sub("flightFast"), g, isFast and 1 or 0, 1)
    if f.n == 2 then keep(sub("flightPace"), paceKey(g, isFast), dur / ref, 1000) end
    local s1, s2 = dataTime(f.ids, f.n, isFast, "short"), dataTime(f.ids, f.n, isFast, "full")
    if f.n > 2 and s1 and s2 and abs(s1 - s2) >= JOIN_VOTE then
      keep(settings(), "flightJoins", model == "full" and 0 or 1, 1)
    end
  end
  FL.learned = FL.learned + 1
  FL.lastFlight.learned = true
end

-- Each leg's end, seconds from take-off, scaled to the flight's estimate (nil when unknown).
local function legEnds(f)
  if not f.known or not plain(f.est) then return nil end
  local legs = legTimes(f.ids, f.n, f.fast)
  if not legs then return nil end
  local total, ends = 0, {}
  for i = 1, #legs do
    total = total + legs[i]
    ends[i] = total
  end
  if total <= 0 then return nil end
  for i = 1, #ends do ends[i] = ends[i] * f.est / total end
  return ends
end

-- An early landing (the leave button on a flight): it comes down at the next place on the route.
local function earlyLanding()
  local f = cur
  if not f then return end
  f.learn = false
  local ends = legEnds(f)
  local t = now()
  if not ends or not t then return end
  local el = t - f.gt
  for i = 1, #ends do
    if ends[i] > el then
      f.est, f.dest = ends[i], shortName(f.names[i + 1])
      break
    end
  end
  if bar then bar.glLine = nil end
  FL.placedAt = nil   -- (another place's name: the big timer's place again now)
  draw()
end

---------------------------------------------------------------------------
-- After a /reload or a relog in the air
---------------------------------------------------------------------------
local function decodeTrack(s)
  local pts = {}
  for x, y in sgmatch(s, "(%-?%d+),(%-?%d+)") do pts[#pts + 1] = { tonumber(x), tonumber(y) } end
  return pts
end

-- How far into the route you are, from where you are (seconds on the estimate's clock), or nil
-- (and true when you are known to be off the route: some other flight).
local function progress(f)
  local x, y = position()
  if not x or not f.known then return nil end
  local best, bestD, off = nil, nil, 0
  for i = 1, f.n - 1 do
    local k = f.ids[i] .. ">" .. f.ids[i + 1]
    local secs, tr = EDGES[k], TRACKS[k]
    if not secs or not tr then return nil end
    local pts = decodeTrack(tr)
    for j = 1, #pts - 1 do
      local a, b = pts[j], pts[j + 1]
      local ta = (j - 1) * TRACK_STEP
      local tb = (j == #pts - 1) and secs or j * TRACK_STEP
      local vx, vy = b[1] - a[1], b[2] - a[2]
      local len2 = vx * vx + vy * vy
      local u = len2 > 0 and max(0, min(1, ((x - a[1]) * vx + (y - a[2]) * vy) / len2)) or 0
      local px, py = a[1] + vx * u - x, a[2] + vy * u - y
      local d = px * px + py * py
      if not bestD or d < bestD then best, bestD = off + ta + (tb - ta) * u, d end
    end
    off = off + secs
  end
  if not best or off <= 0 then return nil end
  if bestD > OFF_ROUTE * OFF_ROUTE then return nil, true end
  local est = plain(f.est)
  return est and best * est / off or best
end
FL.Progress = progress

local function validSaved(f)
  if type(f) ~= "table" or type(f.ids) ~= "table" or type(f.names) ~= "table" then return false end
  if not plain(f.n) or f.n < 2 or not plain(f.gt) or type(f.key) ~= "string" or type(f.dest) ~= "string" then return false end
  if type(f.who) ~= "string" then return false end
  if f.est ~= nil and not plain(f.est) then return false end
  for i = 1, f.n do
    if f.names[i] == nil or f.ids[i] == nil then return false end
  end
  return true
end

local function dropSaved()
  settings().flightNow = nil
end

-- The saved flight goes on: the same clock after a /reload, else from where you are.
local function resumeNow(rs)
  local f = rs.f
  local t, st = now(), serverNow()
  local byServer = st and plain(f.st) and (st - f.st) or nil
  local same = rs.reload and t and t >= f.gt and byServer and abs((t - f.gt) - byServer) <= 3
  local how = "reload"
  if not same then
    local el, off = progress(f)
    how = "position"
    if not el and not off then el, how = byServer, "server" end   -- no position (or no track): the server's clock
    if not el or not t then
      dropSaved()   -- off the saved route: that flight is over, this is another one
      return
    end
    f.gt = t - el
    f.learn = false   -- a resumed flight is not timed
  end
  cur = f
  settings().flightNow = f
  FL.resumed = how
  lastUp = t
  boatsAgain(false)
  showBar()
end

local function enterWorld(isLogin, isReload)
  if cur then   -- a loading screen on the way: only Alterac Valley's flights (no data) are timed through one
    if cur.known and dataTime(cur.ids, cur.n, false, "full") then cur.learn = false end
    return
  end
  local S = settings()
  local f = S.flightNow
  if f == nil then return end
  if not validSaved(f) then
    dropSaved()
    return
  end
  if f.who ~= who() then return end   -- another character's flight: kept for that one
  local st = serverNow()
  if st and plain(f.st) and (st - f.st) > (plain(f.est) or 600) + 3600 then
    dropSaved()
    return
  end
  resume = { f = f, at = now() or 0, reload = isReload == true }
  wake()
end

---------------------------------------------------------------------------
-- The watcher: runs only from a click on the map until the flight ends
---------------------------------------------------------------------------
local watcher, waitLeft, offSince = nil, 0, nil

local function step()
  FL.polls = FL.polls + 1
  local t = now()
  local up = flying()
  if cur then
    if up then
      offSince, lastUp = nil, t
      draw()
    elseif not t then
      land(nil)
    elseif not offSince then
      offSince = t
      if not lastUp or t - lastUp > GAP_MAX then cur.learn = false end   -- landed while nothing looked
    elseif t - offSince >= OFF_CONFIRM then
      land(offSince)   -- off the taxi for half a second (a blip on a map change is not a landing)
      offSince = nil
    end
  elseif pending then
    if up and t then
      local p = pending
      pending = nil
      takeoff(p, t)
    elseif not t or t - pending.at > TAKEOFF_WAIT then
      pending = nil
    end
  elseif resume then
    if up then
      local rs = resume
      resume = nil
      resumeNow(rs)
    elseif not t or t - resume.at > RESUME_WAIT then
      resume = nil
      dropSaved()
    end
  end
  if not cur and not pending and not resume and watcher then watcher:Hide() end
end
FL.Step = step

wake = function()
  if not watcher then
    local make = _G.CreateFrame
    if type(make) ~= "function" then return end
    watcher = make("Frame")   -- no parent: it runs while the interface is hidden too (Alt+Z)
    watcher:SetScript("OnUpdate", function(_, elapsed)
      waitLeft = waitLeft - (tonumber(elapsed) or 0)
      if waitLeft > 0 then return end
      waitLeft = 0.1
      local ok, err = pcall(step)
      if not ok then FL.lastError = err end
    end)
  end
  waitLeft = 0
  watcher:Show()
end
FL.Watcher = function() return watcher end
FL.State = function() return cur, pending, resume end

