local function flightsCommand(rest)
  rest = slower(rest or "")
  if rest == "" then
    if not isOn() then
      setOn(true)
      if cur then cur.hidden = false end
      showBar()
      say("flight timers are on: flight times on the flight map, and a countdown while you fly.")
    elseif cur and cur.hidden then
      cur.hidden = false
      showBar()
      say("the flight timer is back.")
    else
      say("flight timers are on. /gl flights off turns them off.")
    end
  elseif rest == "on" or rest == "show" then
    setOn(true)
    if cur then cur.hidden = false end
    showBar()
    say("flight timers are on: flight times on the flight map, and a countdown while you fly.")
  elseif rest == "off" or rest == "hide" then
    setOn(false)
    say("flight timers are off. /gl flights on brings them back.")
  elseif rest == "big" or rest == "small" then
    setBig(rest == "big")
  elseif rest == "status" then
    statusLines()
  else
    say("unknown choice. Use /gl flights on, off, big, small or status.")
  end
end
FL.Command = flightsCommand

local baseSlash = ns.HandleSlash
function ns.HandleSlash(msg)
  local m = type(msg) == "string" and msg or ""
  local cmd, rest = smatch(m, "^%s*(%S*)%s*(.-)%s*$")
  cmd = slower(cmd or "")
  if cmd == "flights" or cmd == "flight" or cmd == "fly" then
    local ok, err = pcall(flightsCommand, rest)
    if not ok then
      FL.lastError = err
      say("flights: " .. tostring(err))
    end
    return
  end
  if type(baseSlash) == "function" then baseSlash(msg) end
  if cmd == "help" or cmd == "?" then
    say("/gl flights : flight times on the flight map, and a countdown while you fly (on, off, big, small, status)")
  end
end

