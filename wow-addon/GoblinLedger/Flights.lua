local function tipLine(button)
  if not isOn() or not isFrame(button) or type(button.GetID) ~= "function" then return end
  local ok, slot = pcall(button.GetID, button)
  if not ok or call(_G.TaxiNodeGetType, slot) ~= "REACHABLE" then return end
  local r = readRoute(slot)
  if not r then return end
  lastTip = { slot = slot, r = r }
  local secs, mine = routeTime(r)
  if not secs then return end
  local tt = _G.GameTooltip
  if not isFrame(tt) or type(tt.AddLine) ~= "function" then return end
  local c = colour("text")
  tt:AddLine((mine and "Flight time: " or "Flight time: about ") .. clock(secs + 0.5), c[1], c[2], c[3])
  tt:Show()
end

local function onTakeNode(slot)
  if not isOn() or cur then return end
  -- The map is still open; if the game has let go of its routes already, the one its tooltip showed.
  local r = readRoute(slot) or (lastTip and lastTip.slot == plain(slot) and lastTip.r) or nil
  if not r then return end
  local isFast = fast()
  local est, mine = routeTime(r, isFast)
  pending = { r = r, est = est, mine = mine, fast = isFast, at = now() or 0 }
  wake()
end

