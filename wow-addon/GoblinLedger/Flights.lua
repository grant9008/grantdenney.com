local function paceKey(g, isFast) return isFast and (g .. " ff") or g end

-- Your real times against the data's, one-hop flights at that speed, the last few: nil until two.
local function pace(isFast)
  local P = settings().flightPace
  local mine = type(P) == "table" and list(P[paceKey(who(), isFast)]) or {}
  if #mine < 2 then return nil end
  return max(0.85, min(1.15, median(mine)))
end

-- Frequent Flier: the talent, or most of your last flights came in at its speed.
local function fast()
  if ffKnown() then return true end
  local F = settings().flightFast
  local v = type(F) == "table" and list(F[who()]) or {}
  return #v >= 2 and median(v) > 0.5
end

local function timesKey(key, isFast) return isFast and (key .. " ff") or key end

-- Your own time for a route (the middle of the last few; of two, the one nearer ref), or nil.
local function own(key, isFast, ref)
  local T = settings().flightTimes
  if type(T) ~= "table" then return nil end
  local l = list(T[timesKey(key, isFast)])
  if #l == 2 and ref then return abs(l[1] - ref) <= abs(l[2] - ref) and l[1] or l[2] end
  return median(l)
end

local function ffSeconds(s) return 0.56 + (s - 0.56) / FF_SPEED end
local function at(s, isFast) return isFast and ffSeconds(s) or s end

-- How the game joins two paths at a place it flies past: "short" (it cuts the corner, JUNC) unless
-- your own multi-hop flights came in nearer "full" (both paths flown whole).
local function joinModel()
  local v = list(settings().flightJoins)
  if #v > 0 and median(v) < 0.5 then return "full" end
  return "short"
end
FL.JoinModel = joinModel

-- The seconds saved over the places a route flies past, at a speed.
local function joins(ids, n, isFast, model)
  local s = 0
  for i = 2, n - 1 do
    local save = JOIN_FULL
    if model ~= "full" then
      save = JUNC[tostring(ids[i - 1]) .. ">" .. tostring(ids[i]) .. ">" .. tostring(ids[i + 1])] or JOIN_GUESS
    end
    s = s + at(save, isFast)
  end
  return s
end

-- The data's time for a route at a speed with a kind of join, nil when a leg is not in the data.
local function dataTime(ids, n, isFast, model)
  local total = 0
  for i = 1, n - 1 do
    local d = plain(ids[i]) and plain(ids[i + 1]) and EDGES[ids[i] .. ">" .. ids[i + 1]]
    if not d then return nil end
    total = total + at(d, isFast)
  end
  return max(1, total - joins(ids, n, isFast, model))
end
FL.DataTime = dataTime

-- Each leg's time (your own, else the data's at your pace), nil when a leg is not in the data.
local function legTimes(ids, n, isFast)
  local p = pace(isFast) or 1
  local legs = {}
  for i = 1, n - 1 do
    local a, b = ids[i], ids[i + 1]
    if not plain(a) or not plain(b) then return nil end
    local k = a .. ">" .. b
    local d = EDGES[k]
    local t = own(k, isFast, d and at(d, isFast))
    if not t then
      if not d then return nil end
      t = at(d, isFast) * p
    end
    legs[i] = t
  end
  return legs
end

-- A route's time: seconds and true when it is your own time for that exact route.
local function routeTime(r, isFast)
  if isFast == nil then isFast = fast() end
  local model = joinModel()
  local mine = own(r.key, isFast, r.known and dataTime(r.ids, r.n, isFast, model) or nil)
  if mine then return mine, true end
  if not r.known then return nil end
  local legs = legTimes(r.ids, r.n, isFast)
  if not legs then return nil end
  local total = 0
  for i = 1, #legs do total = total + legs[i] end
  return max(1, total - joins(r.ids, r.n, isFast, model)), false
end
FL.RouteTime = routeTime

