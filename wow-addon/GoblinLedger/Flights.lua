local function median(t)
  local n = #t
  if n == 0 then return nil end
  local s = {}
  for i = 1, n do s[i] = t[i] end
  tsort(s)
  if n % 2 == 1 then return s[(n + 1) / 2] end
  return (s[n / 2] + s[n / 2 + 1]) / 2
end
