local slotIDs   -- slot -> node id on the open map (C_TaxiMap), cleared when a map opens or closes
local lastTip   -- { slot, r }: the route last read for the map's tooltip, cleared when a map opens

local function mapIDs()
  if slotIDs then return slotIDs end
  local map = {}
  local CT = _G.C_TaxiMap
  local mapID = plain(call(_G.GetTaxiMapID))
  if mapID and type(CT) == "table" and type(CT.GetAllTaxiNodes) == "function" then
    local ok, nodes = pcall(CT.GetAllTaxiNodes, mapID)
    if ok and type(nodes) == "table" then
      for _, n in ipairs(nodes) do
        if type(n) == "table" then
          local s, id = plain(n.slotIndex), plain(n.nodeID)
          if s and id then map[s] = id end
        end
      end
    end
  end
  slotIDs = map
  return map
end

-- Without C_TaxiMap: the node with the slot's name, the nearest one on the map when names repeat.
local function guessID(slot, name)
  if not name then return nil end
  local x, y = call(_G.TaxiNodePosition, slot)
  x, y = plain(x), plain(y)
  local best, bestD
  for id, n in pairs(NODES) do
    if n[1] == name then
      local d = 0
      if x and y and n[4] then d = (n[4] - x) * (n[4] - x) + (n[5] - y) * (n[5] - y) end
      if not bestD or d < bestD or (d == bestD and id < best) then best, bestD = id, d end
    end
  end
  return best
end

-- The route the game will fly to a slot: its hops as the game gives them (never worked out here).
-- { key, ids, names, n, known } or nil.
local function readRoute(slot)
  slot = plain(slot)
  if not slot then return nil end
  local hops = plain(call(_G.GetNumRoutes, slot))
  if not hops or hops < 1 or hops > 30 then return nil end
  local slots = { plain(call(_G.TaxiGetNodeSlot, slot, 1, true)) }
  if not slots[1] then return nil end
  for i = 1, hops do
    local s = plain(call(_G.TaxiGetNodeSlot, slot, i, false))
    if not s then return nil end
    slots[i + 1] = s
  end
  if slots[hops + 1] ~= slot then return nil end
  local map = mapIDs()
  local r = { ids = {}, names = {}, n = hops + 1, known = true }
  for i, s in ipairs(slots) do
    local name = text(call(_G.TaxiNodeName, s))
    local id = map[s] or guessID(s, name)
    r.ids[i] = id or false
    r.names[i] = name or (id and NODES[id] and NODES[id][1]) or "?"
    if not id then r.known = false end
  end
  r.key = tconcat(r.known and r.ids or r.names, ">")
  return r
end
FL.ReadRoute = readRoute

