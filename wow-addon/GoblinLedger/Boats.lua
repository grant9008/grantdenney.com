-- The track's direction from stop st as the boat leaves it.
local function leavesThisWay(st, dx, dy)
  local rt = st.rt
  local tr = track(rt)
  local want = st.arr + st.wait + 12
  for i = 1, #tr - 1 do
    local p, q = tr[i], tr[i + 1]
    if p[1] <= want and q[1] >= want and p[2] == st.inst and q[2] == st.inst then
      local u = (want - p[1]) / max(0.001, q[1] - p[1])
      local ex, ey = p[3] + u * (q[3] - p[3]) - st.x, p[4] + u * (q[4] - p[4]) - st.y
      local n1, n2 = sqrt(ex * ex + ey * ey), sqrt(dx * dx + dy * dy)
      if n1 < 1 or n2 <= 0 then return true end
      return (ex * dx + ey * dy) / (n1 * n2) >= 0.3
    end
  end
  return true
end

-- Where on a boat's track the player is (moving vx, vy): route and t, unless two boats fit.
local function matchTrack(x, y, inst, vx, vy)
  local best, second
  local vn = sqrt(vx * vx + vy * vy)
  if vn <= 0 then return nil end
  for _, rt in ipairs(R) do
    local tr = track(rt)
    for i = 1, #tr - 1 do
      local p, q = tr[i], tr[i + 1]
      if p[2] == inst and q[2] == inst and q[1] - p[1] <= 5.5 then
        local sx, sy = q[3] - p[3], q[4] - p[4]
        local L2 = sx * sx + sy * sy
        if L2 > 1 then
          local u = ((x - p[3]) * sx + (y - p[4]) * sy) / L2
          if u >= -0.1 and u <= 1.1 then
            u = min(1, max(0, u))
            local d = dist(x, y, p[3] + u * sx, p[4] + u * sy)
            if d <= 35 and (vx * sx + vy * sy) / (vn * sqrt(L2)) >= 0.8 then
              local c = { rt = rt, t = p[1] + u * (q[1] - p[1]), d = d }
              if not best or d < best.d then
                if best and best.rt ~= rt then second = best end
                best = c
              elseif rt ~= best.rt and (not second or d < second.d) then
                second = c
              end
            end
          end
        end
      end
    end
  end
  if not best or (second and second.d <= best.d * 1.5 + 5) then return nil end
  return best
end
B.MatchTrack = matchTrack

-- The stop the boat left last before track time t.
local function previousStop(rt, t)
  local from, fb = 1, nil
  for j, st in ipairs(rt.stops) do
    local back = (t - st.arr - st.wait) % rt.P
    if not fb or back < fb then from, fb = j, back end
  end
  return from
end

local function departed(rest, T, x, y)
  local st = rest.st
  RD.rest, RD.cand, RD.fast = nil, nil, nil
  if not leavesThisWay(st, x - rest.x, y - rest.y) then return end
  RD.ride = { rt = st.rt, from = st.i, dep = T }
  observe(st.rt, st.i, T - st.wait, 1.5, "R")
end

-- The boat stopped (the place stands still again): at one of the route's docks, that is
-- the arrival, from the last second it still moved (it slows down at 1 yd/s each second).
-- Standing still anywhere else (a lag spike, a loading screen on the way) is no arrival.
local function arrived(now, x, y, inst)
  local ride, f = RD.ride, RD.fast
  local rt, stop = ride.rt, nil
  for _, st in ipairs(rt.stops) do
    if st.inst == inst and dist(x, y, st.x, st.y) <= st.r + 30 then stop = st end
  end
  if not stop then return end
  RD.ride, RD.fast = nil, nil
  if not f or f.v > 4 or now - f.t > 3.5 then return end
  local T = f.t + f.v / ACC
  if T > now + 0.5 then return end
  if ride.dep then
    local leg = legTime(rt, ride.from, stop.i, period(rt))
    if abs((T - ride.dep) - leg) > 15 then return end
  end
  observe(rt, stop.i, T, 1.5, "R")
end

local function sampleRide(now, x, y, inst)
  B.stats.samples = B.stats.samples + 1
  local moving = selfMoving()
  local L = RD.last
  RD.last = { t = now, x = x, y = y, inst = inst, own = moving }
  if not L or L.inst ~= inst or now <= L.t or now - L.t > 6 then
    RD.rest, RD.cand, RD.carried = nil, nil, 0
    return
  end
  local dt = now - L.t
  local step = dist(x, y, L.x, L.y)
  if step > 60 * dt then   -- a blink, a charge or a portal: whatever was going on is over
    RD.rest, RD.cand, RD.carried, RD.fast, RD.ride = nil, nil, 0, nil, nil
    return
  end
  if moving or L.own then  -- walking about (on deck too): no rest place, the ride goes on
    RD.rest, RD.cand, RD.carried = nil, nil, 0
    return
  end
  if step < 0.05 then
    if RD.ride then arrived(now, x, y, inst) end
    local rest = RD.rest
    if not rest or dist(x, y, rest.x, rest.y) > 0.3 then
      local a = docksHere(x, y, inst, 0)[1]
      RD.rest = { x = x, y = y, since = L.t, st = a and a.d <= a.st.r and a.st or nil }
    end
    RD.cand, RD.carried = nil, 0
    return
  end
  -- Carried: the place moves while the player does not.
  local v = step / dt
  if v >= 0.8 then RD.fast = { t = (L.t + now) / 2, v = v } end
  local rest = RD.rest
  if rest and rest.st and not RD.ride then
    local d = dist(x, y, rest.x, rest.y)
    if d >= 0.4 and d <= 80 and now - rest.since >= 2 then
      local T = now - sqrt(2 * d / ACC)   -- it started from rest at 1 yd/s each second
      if T >= rest.since - 1 then
        if RD.cand and abs(RD.cand - T) <= 0.75 then
          departed(rest, (RD.cand + T) / 2, x, y)
          return
        end
        RD.cand = T
      end
    end
    return
  end
  if not RD.ride then
    RD.carried = (v >= 10 and v <= 40) and RD.carried + 1 or 0
    if RD.carried >= 2 then
      local m = matchTrack(x, y, inst, x - L.x, y - L.y)
      if m then
        RD.ride = { rt = m.rt, from = previousStop(m.rt, m.t), dep = nil }
        observe(m.rt, nil, now - m.t, 4, "T")
      end
    end
  end
end

-- A loading screen while riding: the boat reached one of its map changes.
local function leavingWorld()
  local ride, L = RD.ride, RD.last
  if ride and L and not L.own then
    ride.load, ride.loadFrom = serverNow(), L.inst
  end
end
local function enteredWorld(isLogin, isReload)
  local ride = RD.ride
  RD.last, RD.rest, RD.cand, RD.carried = nil, nil, nil, 0
  if isLogin or isReload then
    RD.ride = nil
    return
  end
  if not ride or not ride.load then return end
  local x, _, inst = pos()
  local at = ride.load
  ride.load = nil
  if not x or not at then return end
  for _, tp in ipairs(ride.rt.tele) do
    if tp.from == ride.loadFrom and tp.to == inst and tp.from ~= tp.to then
      observe(ride.rt, nil, at - tp.t, 2.5, "L")
      return
    end
  end
end

