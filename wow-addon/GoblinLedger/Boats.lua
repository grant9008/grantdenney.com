    if st.inst == inst then
      local d = dist(x, y, st.x, st.y)
      if d <= st.r + slack then list[#list + 1] = { st = st, d = d } end
    end
  end
  tsort(list, function(p, q) return p.d < q.d end)
  local out = {}
  for _, e in ipairs(list) do
    if not have[e.st.rt] then
      have[e.st.rt] = true
      out[#out + 1] = e
    end
  end
  if out[1] then
    local more = {}
    for _, b in ipairs(out[1].st.group) do
      if not have[b.rt] then
        have[b.rt] = true
        more[#more + 1] = { st = b, d = dist(x, y, b.x, b.y) }
      end
    end
    tsort(more, function(p, q) return p.d < q.d end)
    for _, e in ipairs(more) do out[#out + 1] = e end
  end
  while #out > MAX_LINES do out[#out] = nil end
  return out
end
B.DocksHere = docksHere

local function nearestDock(x, y, inst)
  local best, bd = nil, nil
  for _, st in ipairs(ALL) do
    if st.inst == inst then
      local d = dist(x, y, st.x, st.y)
      if not bd or d < bd then best, bd = st, d end
    end
  end
  return best, bd
end

