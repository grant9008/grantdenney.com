-- The boat's track (every 5 s while it moves), read the first time it is needed.
local function track(rt)
  if rt.track then return rt.track end
  local tr = {}
  for t, inst, x, y in sgmatch(rt.trackSrc, "([%-%d%.]+),(%d+),([%-%d%.]+),([%-%d%.]+)") do
    tr[#tr + 1] = { tonumber(t), tonumber(inst), tonumber(x), tonumber(y) }
  end
  rt.track = tr
  return tr
end
