-- Puts texts in the holder at "below" (under the minimap) or "left" (beside its bottom);
-- returns the screen rectangle it takes, or nil when there is no minimap to hang on.
local function apply(texts, where)
  local h = UI.holder
  local w = 10
  for i = 1, MAX_LINES do
    local t = texts[i]
    UI.fs[i]:SetText(t or "")
    if t then
      local sw = tonumber(call(UI.fs[i], "GetStringWidth")) or (#t * 6)
      w = max(w, sw + 6)
      UI.btn[i]:Show()
    else
      UI.btn[i]:Hide()
    end
  end
  for i = 1, MAX_LINES do UI.btn[i]:SetWidth(w) end
  local H = #texts * LINE_H
  local hw = w + (UI.x and X_GAP + X_SIZE or 0)   -- the lines, then the X at the right end
  h:SetSize(hw, H)
  h:ClearAllPoints()
  local target, mm = minimapParts()
  local hes = call(h, "GetEffectiveScale") or 1
  local W, HH = hw * hes, H * hes
  local sl, sb, sr, stp = rectOf(_G.UIParent)
  if not target then
    h:SetPoint("TOPRIGHT", _G.UIParent, "TOPRIGHT", -16, -262)
    return nil
  end
  local tl, tb, tr, tt = rectOf(target)
  if not tl then   -- not laid out yet: under it, the place checked on the next update
    h:SetPoint("TOP", target, "BOTTOM", 0, -GAP)
    return nil
  end
  local ml, mb, mr, mt = rectOf(mm)
  if not (shown(mm) and ml) then ml, mb, mr, mt = tl, tb, tr, tt end
  if where == "left" then
    h:SetPoint("BOTTOMRIGHT", mm, "BOTTOMLEFT", -12, 0)   -- clear of the map's border too
    return { ml - 12 * hes - W, mb, ml - 12 * hes, mb + HH }
  end
  local cx = (ml + mr) / 2
  if sr and cx + W / 2 > sr - 4 * hes then cx = sr - 4 * hes - W / 2 end
  if sl and cx - W / 2 < sl + 4 * hes then cx = sl + 4 * hes + W / 2 end
  local dx = (cx - (tl + tr) / 2) / hes
  local top = tb - GAP * hes
  if sb and top - HH < sb then   -- a minimap at the bottom of the screen: above it
    h:SetPoint("BOTTOM", target, "TOP", dx, GAP)
    return { cx - W / 2, tt + GAP * hes, cx + W / 2, tt + GAP * hes + HH }
  end
  h:SetPoint("TOP", target, "BOTTOM", dx, -GAP)
  return { cx - W / 2, top - HH, cx + W / 2, top }
end

-- Every line under the minimap; else one joined line there; else that line beside the
-- minimap's bottom; else (nothing free) the joined line under the minimap anyway.
local function layout(texts, joined)
  local tries = { { texts, "below", "stacked" } }
  if #texts > 1 then tries[#tries + 1] = { { joined }, "below", "joined" } end
  tries[#tries + 1] = { { joined }, "left", "left" }
  for _, tr in ipairs(tries) do
    local rect = apply(tr[1], tr[2])
    UI.mode, UI.rect = tr[3], rect
    if not rect or not overlapsAny(rect) then return end
  end
  UI.rect = apply({ joined }, "below")
  UI.mode = "joined"
end

