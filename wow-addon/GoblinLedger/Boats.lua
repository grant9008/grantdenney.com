local prefixOK = false
local function registerPrefix()
  if prefixOK then return true end
  local api = _G.C_ChatInfo
  if type(api) == "table" and type(api.RegisterAddonMessagePrefix) == "function" then
    -- 0 Success, 1 DuplicatePrefix (already ours); 2 InvalidPrefix and 3 MaxPrefixes (the
    -- client's limit is full) mean nothing is received or sent.
    local ok, res = pcall(api.RegisterAddonMessagePrefix, PREFIX)
    prefixOK = ok and (res == nil or res == true or res == 0 or res == 1)
  end
  return prefixOK
end
B.RegisterPrefix = registerPrefix

local function send(msg, ch, now)
  local api = _G.C_ChatInfo
  if type(api) ~= "table" or type(api.SendAddonMessage) ~= "function" or not registerPrefix() then return false end
  if SH.bucketAt then SH.bucket = min(8, SH.bucket + (now - SH.bucketAt) / 5) end
  SH.bucketAt = now
  if SH.bucket < 1 then return false end
  SH.bucket = SH.bucket - 1
  local ok, res = pcall(api.SendAddonMessage, PREFIX, msg, ch)
  -- Anything but success (a trial account, the game's throttle, not in a group): not shared, say nothing.
  if ok and (res == nil or res == true or res == 0) then
    B.stats.sent = B.stats.sent + 1
    SH.out[#SH.out + 1] = ch .. " " .. msg
    if #SH.out > 20 then table.remove(SH.out, 1) end
    return true
  end
  return false
end

local function anchorMessage(rt, rec, now)
  local j = rec.obs > 0 and rec.obs or 1
  local P = period(rt)
  local T = rec.t0 + rt.stops[j].arr
  T = T + floor((now - T) / P) * P   -- the latest arrival at that stop
  local sg = min(30, max(1, floor(sigma(rt, rec, j, now) + 0.999)))
  return sformat("A1|%d|%d|%.1f|%d|%s|%.3f|%s", rt.path, j, T, sg, rec.src, P, rt.ver)
end
B.AnchorMessage = anchorMessage

local function shareOwn(rt, now)
  local rec = anchorOf(rt, now)
  if not rec or rec.src == "G" then return end
  for _, ch in ipairs(channels()) do
    local k = rt.path .. ch
    if not SH.sentAt[k] or now - SH.sentAt[k] >= 60 then
      if send(anchorMessage(rt, rec, now), ch, now) then SH.sentAt[k] = now end
    end
  end
end

local function ask(rt, now)
  for _, ch in ipairs(channels()) do
    local k = rt.path .. ch
    if not SH.askAt[k] or now - SH.askAt[k] >= 300 then
      SH.askAt[k] = now
      send("Q1|" .. rt.path, ch, now)
    end
  end
end

