local function isSelf(sender)
  local me = callG("UnitName", "player")
  if type(me) ~= "string" then return false end
  local realm = callG("GetNormalizedRealmName")
  return sender == me or (type(realm) == "string" and sender == me .. "-" .. realm)
end

local CHANNELS = { GUILD = true, PARTY = true, RAID = true, INSTANCE_CHAT = true }

local function reply(rt, ch, asked)
  local now = serverNow()
  if not now or not isOn() then return end
  if (SH.answeredAt[rt.path] or -1e9) >= asked - 2 then return end   -- someone else answered
  local rec = anchorOf(rt, now)
  if not rec or rec.src == "G" or sigma(rt, rec, rec.obs, now) > 10 then return end
  if SH.replyAt[rt.path] and now - SH.replyAt[rt.path] < 30 then return end
  SH.replyAt[rt.path] = now
  send(anchorMessage(rt, rec, now), ch, now)
end

local function onAddonMessage(prefix, text, ch, sender)
  if isSecret(prefix) or prefix ~= PREFIX then return end
  if not isOn() then return end
  if isSecret(text) or isSecret(ch) or isSecret(sender) then return end
  if type(text) ~= "string" or type(sender) ~= "string" or #text > 255 or not CHANNELS[ch] or isSelf(sender) then return end
  local now = serverNow()
  if not now then return end
  local e = SH.senders[sender]
  if not e or now - e.t > 600 then
    e = { t = now, n = 0 }
    SH.senders[sender] = e
  end
  e.n = e.n + 1
  if e.n > 20 then
    B.stats.dropped = B.stats.dropped + 1
    return
  end
  local q = smatch(text, "^Q1|(%d+)$")
  if q then
    local rt = byPath[tonumber(q)]
    if not rt then B.stats.dropped = B.stats.dropped + 1 return end
    B.stats.got = B.stats.got + 1
    local rec = anchorOf(rt, now)
    if rec and rec.src ~= "G" then
      local rnd = B.rand or math.random
      local wait = 1 + 3 * (tonumber(rnd()) or 0.5)
      local timer = _G.C_Timer
      if type(timer) == "table" and type(timer.After) == "function" then
        timer.After(wait, function()
          local ok, err = pcall(reply, rt, ch, now)
          if not ok then B.lastError = err end
        end)
      end
    end
    return
  end
  local p, j, T, sg, src, P = smatch(text, "^A1|(%d+)|(%d)|(%d+%.?%d?)|(%d+)|([RLTAM])|(%d+%.%d+)$")
  local rt = p and byPath[tonumber(p)]
  j, T, sg, P = tonumber(j), tonumber(T), tonumber(sg), tonumber(P)
  if not (rt and j and T and sg and P) or j < 1 or j > #rt.stops or sg < 1 or sg > 30
     or T < now - MAX_AGE or T > now + rt.P + 5 or abs(P - rt.P) > rt.P * 0.005 then
    B.stats.dropped = B.stats.dropped + 1
    return
  end
  B.stats.got = B.stats.got + 1
  SH.answeredAt[rt.path] = now
  -- The sender's error, one more second (clocks differ), and its age in round trips.
  local _, sP = period(rt)
  local s = sg + 1 + (abs(now - T) / rt.P) * sP
  if s > ABOUT_S then
    B.stats.dropped = B.stats.dropped + 1
    return
  end
  observe(rt, j, T, s, "G", sender)
end
B.OnAddonMessage = onAddonMessage

