local D = { frame = nil, interval = nil, acc = 0, listening = false }
B.driver = D
local step

local function setInterval(sec)
  D.interval = sec
  if not sec then
    if D.frame then D.frame:Hide() end
    return
  end
  if not D.frame then
    local f = _G.CreateFrame("Frame")
    f:Hide()
    f:SetScript("OnUpdate", function(_, elapsed)
      calibrate()
      D.acc = D.acc + (tonumber(elapsed) or 0)
      if D.interval and D.acc >= D.interval then
        D.acc = 0
        local ok, err = pcall(step)
        if not ok then B.lastError = err end
      end
    end)
    D.frame = f
  end
  if not D.frame:IsShown() then
    D.acc = 0
    D.frame:Show()
  end
end

-- CHAT_MSG_MONSTER_SAY / YELL only near a dock whose dockmaster announces.
local function listen(on)
  local f = B.eventFrame
  if on == D.listening or type(f) ~= "table" then return end
  D.listening = on
  for _, ev in ipairs({ "CHAT_MSG_MONSTER_SAY", "CHAT_MSG_MONSTER_YELL" }) do
    if on then pcall(f.RegisterEvent, f, ev) else pcall(f.UnregisterEvent, f, ev) end
  end
end

local function stopAll()
  hideUI()
  listen(false)
  setInterval(nil)
  RD.last, RD.rest, RD.cand, RD.ride, RD.fast, RD.carried = nil, nil, nil, nil, nil, 0
end

step = function()
  B.stats.steps = B.stats.steps + 1
  if not isOn() then stopAll() return end
  local now = serverNow()
  local x, y, inst = pos()
  if not now or not x or callG("IsInInstance") == true then stopAll() return end
  sampleRide(now, x, y, inst)
  local list = docksHere(x, y, inst, UI.shown and 10 or 0)
  if #list > 0 then
    render(list, now)
    for _, e in ipairs(list) do
      local rec = anchorOf(e.st.rt, now)
      if not rec or sigma(e.st.rt, rec, e.st.i, now) > 15 then ask(e.st.rt, now) end
    end
  else
    hideUI()
  end
  local _, d = nearestDock(x, y, inst)
  local announcer = false
  for _, a in ipairs(ANNOUNCERS) do
    local st = byPath[a.path] and byPath[a.path].stops[a.stop]
    if st and st.inst == inst and dist(x, y, st.x, st.y) <= 150 then announcer = true end
  end
  listen(announcer)
  if #list > 0 or RD.ride or RD.carried > 0 or (d and d <= CLOSE_YD) then
    setInterval(1)
  elseif d and d <= NEAR_YD then
    setInterval(3)
  else
    setInterval(nil)
    -- Far from docks: one more look a second later (a /reload or a zone change at sea,
    -- on a boat), then nothing until the next zone change.
    if not D.probed then
      D.probed = true
      local timer = _G.C_Timer
      if type(timer) == "table" and type(timer.After) == "function" then timer.After(1.2, B.Step) end
    end
  end
end
B.Step = function()
  local ok, err = pcall(step)
  if not ok then B.lastError = err end
end

local function wake()
  if not isOn() then return end
  D.probed = false
  B.Step()
end
B.Wake = wake

