-- Seconds from the timer's nearest arrival at stop st to now (+: it arrived that long ago).
local function fromArrival(st, kind, sec)
  if kind == "docked" then return st.wait - sec end
  if kind == "coming" then
    local since = st.rt.P - sec
    if since < sec then return since end
    return -sec
  end
  return nil
end

-- "The boat docks now": when the timer already says so (to within max(5 s, twice its
-- error)), that agrees; else it is a sighting (a better timer that agrees stays).
local function boatNow(st, now)
  local rt = st.rt
  local kind, sec, sg = stopState(rt, st.i, now)
  local off = fromArrival(st, kind, sec)
  local res
  if off and sg <= 10 and abs(off) <= max(5, 2 * sg) then
    local rec = anchorOf(rt, now)
    rec.ok = (tonumber(rec.ok) or 0) + 1
    res = "kept"
  else
    res = observe(rt, st.i, now, 4, "M")
  end
  local what = "the " .. slower(rt.kind) .. " to " .. st.to
  if res == "kept" then
    say("boat timer kept: it already had " .. what .. " docking now.")
  else
    say("boat timer set: " .. what .. " docks now.")
  end
  wake()
end

-- A click: like /gl boat now, but when the timer is good and says the boat is not near (more
-- than 20 s from docking), a second click within 5 s is needed (a stray click must not spoil
-- a good timer).
function B.Click(st)
  local now = serverNow()
  if not now or not isOn() then return end
  local kind, sec, sg = stopState(st.rt, st.i, now)
  local off = fromArrival(st, kind, sec)
  local far = off and sg <= EXACT_S and abs(off) > 20
  local c = UI.confirm
  if far and not (c and c.st == st and now - c.at <= 5) then
    UI.confirm = { st = st, at = now }
    local said = kind == "docked" and ("docked " .. clockText(off) .. " ago") or ("comes in " .. clockText(sec))
    say("the timer says this " .. slower(st.rt.kind) .. " " .. said .. ". Click again if it is docking now.")
    return
  end
  UI.confirm = nil
  boatNow(st, now)
end

local function sourceText(src)
  if src == "R" or src == "T" or src == "L" then return "your ride" end
  if src == "A" then return "the dockmaster" end
  if src == "M" then return "/gl boat now" end
  return "a guild or group member"
end

-- The nearest dock on this continent, how far, and its boats, in one line.
local function nearestText(now)
  local x, y, inst = pos()
  if not x then return nil end
  local st, d = nearestDock(x, y, inst)
  if not st then return nil end
  local list = docksHere(st.x, st.y, st.inst, 0)
  local parts = {}
  for i, e in ipairs(list) do
    local head, value, _, short = lineParts(e.st, now)
    parts[i] = #list > 1 and (e.st.to .. " " .. short) or (head .. ": " .. value)
  end
  return sformat("nearest dock: %s, %d yd. %s", st.place, floor(d + 0.5), tconcat(parts, "; "))
end

-- Where the timers show, for the chat lines.
local function whereText()
  return bigStyle() and "a big timer in the middle of the screen" or "a line under the minimap"
end

-- /gl boats: two lines (on or off, big or small, and the nearest dock with its boats).
local function status()
  if not isOn() then
    say("boat timers are off. /gl boats on turns them on.")
    return
  end
  local x, y, inst = pos()
  if x and hiddenHere(x, y, inst, docksHere(x, y, inst, 0)) then
    say("boat timers are on (" .. (bigStyle() and "big" or "small") .. "), hidden at this dock until you leave it (/gl boats on shows them).")
  elseif bigStyle() and busy() then   -- (a flight or a fight: the small line shows meanwhile)
    say("boat timers are on: big, in the middle of the screen, but on a flight or in a fight the line under the minimap (/gl boats small: always there). /gl boats all lists every route.")
  elseif bigStyle() then
    say("boat timers are on: big, in the middle of the screen (/gl boats small: under the minimap). /gl boats all lists every route.")
  else
    say("boat timers are on: small, under the minimap (/gl boats big: in the middle of the screen). /gl boats all lists every route.")
  end
  local now = serverNow()
  local t = now and nearestText(now)
  if t then say(t) end
end

-- /gl boats all: every route, what is known about it, and the nearest dock.
local function listAll()
  say("boat timers are " .. (isOn() and ("on: at a dock, " .. whereText() .. " says when the boat comes.") or "off. /gl boats on turns them on."))
  local now = serverNow()
  if not now then return end
  for _, rt in ipairs(R) do
    local rec = anchorOf(rt, now)
    local P = period(rt)
    local what = "unknown (ride it, or /gl boat now when it docks)"
    if rec then
      local sg = sigma(rt, rec, rec.obs, now)
      local age = type(ns.AgeText) == "function" and ns.AgeText(now - rec.seen) or ""
      what = (sg <= ABOUT_S and sformat("known to %d s", floor(sg + 0.999))
              or (store().resetKeeps == false and beforeReset(rec, now) and "unknown since the weekly reset" or "too old to trust"))
        .. " (" .. sourceText(rec.src) .. ", " .. age .. ")"
    end
    say(sformat("%s (%s round trip): %s", rt.name, clockText(floor(P + 0.5)), what))
  end
  local t = nearestText(now)
  if t then say(t) end
end

local function boatsCommand(rest)
  rest = slower(rest or "")
  local S = settings()
  if rest == "on" then
    S.boats, S.boatHide = nil, nil   -- (and back at a dock the X hid them at)
    say("boat timers are on: at a dock, " .. whereText() .. " says when the boat comes.")
    wake()
  elseif rest == "big" or rest == "small" then
    S.boatStyle = rest == "small" and "small" or nil   -- (saved; big is the default)
    local msg = rest == "small" and "boat timers are small now: a line under the minimap. /gl boats big makes them big again."
                or "boat timers are big now: in the middle of the screen. /gl boats small puts them under the minimap."
    say(isOn() and msg or (msg .. " They are off: /gl boats on turns them on."))
    wake()
  elseif rest == "off" then
    S.boats = false
    stopAll()
    say("boat timers are off. /gl boats on brings them back.")
  elseif rest == "" or rest == "status" then
    status()
  elseif rest == "all" then
    listAll()
  elseif rest == "now" then
    B.BoatNow()
  else
    say("unknown choice. Use /gl boats on, off, big, small or all.")
  end
end

function B.BoatNow()
  if not isOn() then
    say("boat timers are off. /gl boats on turns them on.")
    return
  end
  local now = serverNow()
  local x, y, inst = pos()
  if not now or not x then
    say("stand on the pier when the boat docks, then type /gl boat now.")
    return
  end
  local e = docksHere(x, y, inst, 60)[1]
  if not e then
    say("you are not at a dock. Stand on the pier when the boat docks, then type /gl boat now.")
    return
  end
  boatNow(e.st, now)
end

local baseSlash = ns.HandleSlash
function ns.HandleSlash(msg)
  local m = type(msg) == "string" and msg or ""
  local cmd, rest = smatch(m, "^%s*(%S*)%s*(.-)%s*$")
  cmd = slower(cmd or "")
  if cmd == "boats" or cmd == "boat" then
    local r = slower(rest or "")
    local ok, err = pcall(boatsCommand, (cmd == "boat" and r == "") and "status" or r)
    if not ok then
      B.lastError = err
      say("boats: " .. tostring(err))
    end
    return
  end
  if type(baseSlash) == "function" then baseSlash(msg) end
  if cmd == "help" or cmd == "?" then
    say("/gl boats : at a dock, when the boat comes (on, off, big, small, all); /gl boat now as a boat docks sets its timer")
  end
end

