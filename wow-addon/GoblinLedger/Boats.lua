local clock = { off = nil, lastS = nil, at = -1e9 }
local function getTime()
  local f = _G.GetTime
  if type(f) == "function" then
    local ok, t = pcall(f)
    if ok and finite(t) and not isSecret(t) then return t end
  end
  return nil
end
local function serverSec()
  local f = _G.GetServerTime
  if type(f) ~= "function" then return nil end
  local ok, s = pcall(f)
  if ok and finite(s) and not isSecret(s) and s > 0 then return s end
  return nil
end
local function serverNow()
  local s = serverSec()
  if not s then return nil end
  if clock.off then
    local g = getTime()
    local t = g and g + clock.off
    if t and t >= s - 0.25 and t < s + 1.25 then return t end
    clock.off = nil
  end
  return s + 0.5
end
B.Now = serverNow
local function calibrate()
  local g = getTime()
  if not g then return end
  if clock.off and g - clock.at < 900 then return end
  local s = serverSec()
  if not s then return end
  if clock.lastS and s ~= clock.lastS then
    if s == clock.lastS + 1 then
      clock.off, clock.at = s - g, g
    end
    clock.lastS = nil
    return
  end
  clock.lastS = s
end
B.clock = clock

