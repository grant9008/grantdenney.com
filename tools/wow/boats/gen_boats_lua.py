"""Writes the route table of wow-addon/GoblinLedger/Boats.lua (the block between
"-- BEGIN DATA" and "-- END DATA") from transports.json.

    python tools/wow/boats/gen_boats_lua.py            # rewrite the block
    python tools/wow/boats/gen_boats_lua.py --check    # exit 1 when the block is out of date

Input: tools/wow/boats/transports.json, the boat research for WoW Forever 1.60.1.70959
(2026-11-19). It was built from the Forever client tables on wago.tools (TaxiPath,
TaxiPathNode, UiMap, UiMapAssignment, AreaTable, Map; build 1.60.1.70959) with a port of
TrinityCore's transport timing (TransportMgr::GeneratePath / Transport::CalculateSegmentPos,
speed 30 and acceleration 1 from MaNGOS-zero's gameobject_template) and checked against the
round trips riders measured for NauticusClassicResurrected (MIT) and Azeroth Tripview's
posted times. Its "about" and "sources" fields say more.

What is kept per route: the round trip (cycle_s, the best value), how far that may be off per
round trip (PERIOD_SIGMA below), each stop (where the boat goes from there, the place, the
continent instance UnitPosition reports, world x and y, the dock radius, when the boat
arrives after t=0 = arriving at the first stop, how long it waits, how far the offset may be
off: STOP_SIGMA), the map changes (loading screens for passengers) and the boat's track
every 5 s while it moves. Plain ASCII; the file keeps CRLF line ends.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
JSON_FILE = os.path.join(HERE, "transports.json")
LUA_FILE = os.path.join(ROOT, "wow-addon", "GoblinLedger", "Boats.lua")
BEGIN, END = "-- BEGIN DATA", "-- END DATA"

# The short names players use, for "Boat to <name>".
SHORT = {
    "Menethil Harbor": "Menethil", "Theramore Isle": "Theramore", "Southshore": "Southshore",
    "Auberdine": "Auberdine", "Rut'theran Village": "Rut'theran", "Stormwind Harbor": "Stormwind",
    "Feathermoon Stronghold": "Feathermoon", "The Forgotten Coast": "Forgotten Coast",
    "Booty Bay": "Booty Bay", "Ratchet": "Ratchet", "Steamwheedle Port": "Tanaris",
    "Powderfuse Port": "Riverglades", "Dalaran": "Dalaran", "Zephras Isle - High Order Dock": "Zephras Isle",
    "Zephras Isle - Windshapers Dock": "Zephras Isle", "Orgrimmar zeppelin tower": "Orgrimmar",
    "Undercity zeppelin tower": "Undercity", "Grom'gol Base Camp": "Grom'gol", "Skywatcher Plateau": "Mulgore",
}
KIND = {"boat": "Boat", "zeppelin": "Zeppelin", "skyship": "Skyship"}
# How far the round trip may be off (s per round trip). Measured classic routes: ms; the
# Forever-only ones were timed by hand or only modelled.
PERIOD_SIGMA = {
    "menethil_theramore": 0.01, "menethil_southshore_auberdine": 0.05, "auberdine_rutheran": 0.2,
    "stormwind_auberdine": 0.5, "feathermoon_ferry": 0.01, "bootybay_ratchet": 0.01,
    "tanaris_riverglades": 0.4, "dalaran_zephras": 1.0, "orgrimmar_undercity": 0.01,
    "orgrimmar_gromgol": 0.01, "undercity_gromgol": 0.05, "mulgore_zephras": 0.3,
}
# How far a stop's arrival offset (from the first stop) may be off, s: the model's leg times.
# Measured routes whose model round trip matches: 0.5; modelled-only ones more; the Mulgore
# skyship's far dock is a guess (the model is 7.3 s short of the measured round trip).
STOP_SIGMA = {
    "menethil_southshore_auberdine": 1.0, "auberdine_rutheran": 1.0, "stormwind_auberdine": 1.5,
    "tanaris_riverglades": 1.5, "dalaran_zephras": 3.0, "undercity_gromgol": 1.0, "mulgore_zephras": 8.0,
}
FACTION = {"Alliance": "A", "Horde": "H", "Neutral": "N"}


def num(v):
    """A short Lua number: no trailing zeros."""
    s = ("%.3f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def lua_str(s):
    if any(ord(c) > 127 for c in s) or '"' in s or "\\" in s:
        raise SystemExit("unexpected text in the data: %r" % s)
    return '"%s"' % s


def dest_label(stops, i):
    """Where the boat goes from stop i: the next stop; on a loop of three, the next two."""
    n = len(stops)
    nxt = [SHORT[stops[(i + k) % n]["name"]] for k in range(1, n)]
    return ", ".join(nxt[:2])


def build(data):
    out = [BEGIN,
           "-- Generated by tools/wow/boats/gen_boats_lua.py from tools/wow/boats/transports.json",
           "-- (WoW Forever 1.60.1.70959 client tables on wago.tools: TaxiPath, TaxiPathNode, AreaTable,",
           "-- UiMap; timing: TrinityCore's transport model at speed 30, acceleration 1, checked against",
           "-- round trips measured by NauticusClassicResurrected riders). Do not edit by hand.",
           "-- Route: { key, TaxiPath id, kind, faction (A, H, N), round trip s, round trip error s, stops,",
           "--          map changes \"t:from>to\", track \"t,instance,x,y;...\" every 5 s while it moves }",
           "-- Stop: { goes to, place, instance, world x, world y, dock radius yd, arrives at s, waits s,",
           "--         offset error s, AreaTable id (0: none known) }",
           "-- t = 0 is the boat arriving at the route's first stop. x, y are UnitPosition's first two returns.",
           "local ROUTES = {"]
    for r in data["routes"]:
        key = r["id"]
        stops = r["stops"]
        out.append("  { %s, %d, %s, %s, %s, %s, {" % (
            lua_str(key), r["taxiPathID"], lua_str(KIND[r["type"]]), lua_str(FACTION[r["faction"].split()[0]]),
            num(r["cycle_s"]), num(PERIOD_SIGMA[key])))
        for i, s in enumerate(stops):
            w = s["world"]
            err = 0 if i == 0 else STOP_SIGMA.get(key, 0.5)
            out.append("      { %s, %s, %d, %s, %s, %d, %s, %s, %s, %d }," % (
                lua_str(dest_label(stops, i)), lua_str(s["name"]), w["mapID"], num(w["x"]), num(w["y"]),
                s["radius_yards"], num(s["arrive_s"]), num(s["wait_s"]), num(err), s["areaID"] or 0))
        tele = ",".join("%s:%d>%d" % (num(t["t_s"]), t["fromMap"], t["toMap"]) for t in r["teleports"])
        out.append("    }, %s," % lua_str(tele))
        pts = ";".join("%s,%d,%s,%s" % (num(p[0]), p[1], num(round(p[2], 1)), num(round(p[3], 1))) for p in r["track"])
        out.append("    %s }," % lua_str(pts))
    out.append("}")
    out.append(END)
    return out


def main(argv):
    check = "--check" in argv
    data = json.load(open(JSON_FILE, encoding="ascii"))
    block = build(data)
    raw = open(LUA_FILE, "rb").read().decode("ascii")
    nl = "\r\n" if "\r\n" in raw else "\n"
    lines = raw.split(nl)
    try:
        a, b = lines.index(BEGIN), lines.index(END)
    except ValueError:
        raise SystemExit("Boats.lua has no %s / %s block" % (BEGIN, END))
    new = nl.join(lines[:a] + block + lines[b + 1:])
    if check:
        if new != raw:
            print("Boats.lua's route table is out of date: run python tools/wow/boats/gen_boats_lua.py")
            return 1
        print("Boats.lua's route table matches transports.json (%d routes)" % len(data["routes"]))
        return 0
    with open(LUA_FILE, "wb") as fh:
        fh.write(new.encode("ascii"))
    print("wrote %d routes into %s" % (len(data["routes"]), LUA_FILE))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
