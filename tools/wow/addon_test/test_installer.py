def test_resolve(base):
    print("pasted game folders")
    box = Box(base, "resolve")
    os.makedirs(os.path.join(box.addons), exist_ok=True)
    other = os.path.join(box.root, "Other", "World of Warcraft")
    os.makedirs(os.path.join(other, "_retail_"))
    g = box.game
    cases = [
        (g, g), ('"%s"' % g, g), ("'%s'" % g, g), ('  "%s\\"  ' % g, g),
        (box.wow, g), ('"%s"' % box.wow, g),
        (os.path.join(g, "Interface", "AddOns"), g), ('"%s"' % os.path.join(g, "Interface", "AddOns", "Questie"), g),
        (os.path.join(g, "Wow.exe"), g), (g.lower(), g.lower()),
        (other, None), (os.path.join(box.root, "missing"), None), ("", None), ('""', None),
    ]
    script = os.path.join(base, "resolve.ps1")
    write(script, ". '%s'\n$in = Get-Content -LiteralPath $args[0] -Raw -Encoding UTF8 | ConvertFrom-Json\n"
                  "$out = @(foreach ($s in $in) { $r = Resolve-GameDir $s; if ($r) { $r } else { '' } })\n"
                  "ConvertTo-Json -InputObject $out -Compress\n" % os.path.join(TOOLS, "common.ps1").replace("'", "''"))
    inp = os.path.join(base, "resolve.json")
    write(inp, json.dumps([c[0] for c in cases]))
    r = subprocess.run([PS, "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", script, inp],
                       env=box.env(), capture_output=True, text=True, timeout=60)
    try:
        got = json.loads(r.stdout.strip())
    except ValueError:
        got = None
        check(False, "Resolve-GameDir output: %r %r" % (r.stdout, r.stderr))
    if got is not None:
        for (text, want), g2 in zip(cases, got):
            eq(g2 or None, want, "Resolve-GameDir(%r)" % text)


def test_install_migrate(base):
    print("install over Forever AH: paste the folder, migrate, Y for updates")
    box = Box(base, "migrate")
    old_install(box)
    legacy_before = {k: v for k, v in tree(box.legacy).items() if k != "addon_dir.txt"}
    questie = tree(os.path.join(box.addons, "Questie"))
    sv2 = read(box.sv("ACC2", "GoblinLedger.lua"))
    # a wrong folder first, then the World of Warcraft folder in quotes, then Enter (= Y)
    code, out = install(box, ["-DataUrl", box.prices1],
                        answers='%s|"%s"|' % (os.path.join(box.root, "nope"), box.wow),
                        tasks="ForeverAH Prices;ForeverAH Collector")
    eq(code, 0, "install exit code (%s)" % out[-600:])
    check("does not look like the WoW Forever folder" in out, "a wrong folder is refused and asked again")
    check("Found WoW Forever in:" in out and box.game in out, "names the game folder it found")
    addon_files_ok(box, "install")
    eq(read(os.path.join(box.dest, "Data.lua")), read(box.prices1), "Data.lua is the downloaded price file")
    check(not os.path.exists(box.old), "the old ForeverAH addon folder is gone")
    eq(tree(os.path.join(box.addons, "Questie")), questie, "other addons untouched")
    eq(read(box.sv("ACC1", "GoblinLedger.lua")), read(box.sv("ACC1", "ForeverAH.lua")), "ACC1 settings copied to GoblinLedger.lua")
    check(os.path.exists(box.sv("ACC1", "ForeverAH.lua")), "ACC1 old settings file kept as a backup")
    eq(read(box.sv("ACC2", "GoblinLedger.lua")), sv2, "ACC2 existing GoblinLedger.lua not overwritten")
    eq(read(os.path.join(box.app, "update_prices.ps1")), read(UPDATER), "updater installed in LOCALAPPDATA\\GoblinLedger")
    eq(read(os.path.join(box.app, "addon_dir.txt"), "r").strip(), box.dest, "addon_dir.txt names the new addon folder")
    eq(read(os.path.join(box.legacy, "addon_dir.txt"), "r").strip(), box.dest, "old updater's addon_dir.txt points at the new folder")
    eq({k: v for k, v in tree(box.legacy).items() if k != "addon_dir.txt"}, legacy_before,
       "the owner's collector, its folder and the old updater are untouched")
    t = box.tasks()
    eq([x for x in t if x.startswith("DELETE")], ["DELETE ForeverAH Prices"], "the old ForeverAH Prices task is removed")
    reg = [x for x in t if x.startswith("REGISTER")]
    eq(len(reg), 1, "one task registered")
    if reg:
        check(reg[0].startswith("REGISTER Goblin Ledger Prices every 30 minutes"), "task name and interval (%s)" % reg[0])
        check("conhost.exe --headless" in reg[0] and "-Quiet" in reg[0], "the task runs hidden and quiet (%s)" % reg[0])
        check(os.path.join(box.app, "update_prices.ps1") in reg[0], "the task runs the installed updater, not the unzipped one")
    check(not any("Collector" in x for x in t), "the collector task is never touched")
    check("Kept your settings" in out, "says the settings were kept")
    check("Prices updated:" in out, "the updater ran and said so")
    log = read(os.path.join(box.app, "update.log"), "r")
    check(" OK " in log, "update.log in LOCALAPPDATA\\GoblinLedger has the run")
    return box


def test_rerun(base, box):
    print("run again: update, newer prices, found by itself, idempotent")
    box.clear_tasks()
    write(os.path.join(box.dest, "Leftover.lua"), "-- from an older version\n")
    code, out = install(box, ["-DataUrl", box.prices2, "-AutoUpdate", "Y"], search=box.game,
                        tasks="ForeverAH Collector;Goblin Ledger Prices")
    eq(code, 0, "re-run exit code (%s)" % out[-600:])
    check("Could not find WoW Forever" not in out, "re-run finds the game without asking")
    addon_files_ok(box, "re-run")
    check(not os.path.exists(os.path.join(box.dest, "Leftover.lua")), "a file the new version no longer has is removed")
    eq(read(os.path.join(box.dest, "Data.lua")), read(box.prices2), "re-run fetched the newer prices")
    t = box.tasks()
    check(not any(x.startswith("DELETE") for x in t), "re-run deletes no task")
    eq(len([x for x in t if x.startswith("REGISTER Goblin Ledger Prices")]), 1, "re-run registers the task again (replace)")
    before = tree(box.root)
    code, out = install(box, ["-DataUrl", box.prices2, "-AutoUpdate", "Y"], search=box.game,
                        tasks="ForeverAH Collector;Goblin Ledger Prices")
    eq(code, 0, "third run exit code")
    after = tree(box.root)
    changed = sorted(k for k in set(before) | set(after) if before.get(k) != after.get(k))
    eq([c for c in changed if not c.endswith(("update.log", "tasks.log", "etag.txt"))], [],
       "a run with nothing new changes nothing but the logs")
    check("already up to date" in out, "third run: prices already up to date")
    # a failed download keeps the prices and still installs
    code, out = install(box, ["-DataUrl", os.path.join(box.root, "missing.lua"), "-AutoUpdate", "N"], search=box.game,
                        tasks="Goblin Ledger Prices")
    eq(code, 0, "failed download: the install itself still works")
    eq(read(os.path.join(box.dest, "Data.lua")), read(box.prices2), "failed download: the prices are kept")
    check("once a download works" in out, "failed download: says what happens")
    check("DELETE Goblin Ledger Prices" in box.tasks(), "answering N removes the automatic update")


def test_uninstall(base, box):
    print("uninstall: asks, removes, keeps settings unless asked, never the collector")
    legacy_before = tree(box.legacy)
    code, out = uninstall(box, answers="n", tasks="Goblin Ledger Prices;ForeverAH Collector")
    eq(code, 1, "uninstall: N cancels")
    check(os.path.isdir(box.dest) and os.path.isdir(box.app), "uninstall: N removes nothing")
    box.clear_tasks()
    code, out = uninstall(box, answers="y|n", tasks="Goblin Ledger Prices;ForeverAH Collector")
    eq(code, 0, "uninstall exit code (%s)" % out[-600:])
    check(not os.path.exists(box.dest), "uninstall removes the addon folder")
    check(not os.path.exists(box.app), "uninstall removes LOCALAPPDATA\\GoblinLedger")
    eq(box.tasks(), ["DELETE Goblin Ledger Prices"], "uninstall removes only the Goblin Ledger Prices task")
    check(os.path.exists(box.sv("ACC1", "GoblinLedger.lua")), "uninstall keeps the settings when told N")
    eq(tree(box.legacy), legacy_before, "uninstall leaves LOCALAPPDATA\\ForeverAH and the collector alone")
    check(os.path.isdir(os.path.join(box.addons, "Questie")), "uninstall leaves other addons alone")
    code, out = uninstall(box, answers="y", tasks="")
    eq(code, 0, "uninstall twice: nothing to do")
    check("not installed" in out, "uninstall twice says so")
    # install again, then remove with the settings
    install(box, ["-DataUrl", box.prices1, "-AutoUpdate", "N"], search=box.game)
    write(box.sv("ACC1", "GoblinLedger.lua.bak"), "ForeverAH_Settings = {}\n")
    code, out = uninstall(box, answers="y|y")
    eq(code, 0, "uninstall with settings: exit code")
    check(not os.path.exists(box.sv("ACC1", "GoblinLedger.lua")) and not os.path.exists(box.sv("ACC1", "GoblinLedger.lua.bak"))
          and not os.path.exists(box.sv("ACC2", "GoblinLedger.lua")), "uninstall Y/Y deletes the GoblinLedger settings")
    check(os.path.exists(box.sv("ACC1", "ForeverAH.lua")), "uninstall leaves the old ForeverAH backups")


def test_edge_cases(base):
    print("not found, someone else's ForeverAH addon, fresh PC")
    box = Box(base, "edge")
    code, out = install(box, ["-DataUrl", box.prices1], answers="")
    eq(code, 1, "game not found and Enter: stops")
    check("Nothing was installed" in out, "game not found: says nothing was installed")
    check(not os.path.exists(box.dest) and not os.path.exists(box.app), "game not found: nothing created")
    # another addon that is also called ForeverAH (not ours: no grantdenney.com in its TOC)
    write(os.path.join(box.old, "ForeverAH.toc"), "## Title: Forever AH\r\n## Notes: Someone else's addon\r\n")
    write(box.sv("ACC1", "ForeverAH.lua"), "ForeverAHDB = {}\n")
    code, out = install(box, ["-DataUrl", box.prices1, "-AutoUpdate", "Y"], search=box.game)
    eq(code, 0, "fresh install exit code (%s)" % out[-600:])
    check(os.path.isfile(os.path.join(box.old, "ForeverAH.toc")), "someone else's ForeverAH addon is left alone")
    check(not os.path.exists(box.sv("ACC1", "GoblinLedger.lua")), "its saved variables are not copied")
    addon_files_ok(box, "fresh install")
    eq(read(os.path.join(box.dest, "Data.lua")), read(box.prices1), "fresh install: prices downloaded")
    check(not any(x.startswith("DELETE") for x in box.tasks()), "fresh install: no task to delete")
    check(not os.path.exists(box.legacy), "fresh install: no LOCALAPPDATA\\ForeverAH made")
    # -GameDir with quotes
    box2 = Box(base, "gamedir")
    code, out = install(box2, ["-GameDir", '"%s"' % box2.game, "-DataUrl", box2.prices1, "-AutoUpdate", "N"])
    eq(code, 0, "-GameDir in quotes works")
    check(not box2.tasks(), "-AutoUpdate N on a fresh PC: no task at all")


def test_release(base):
    print("release zip and running the unzipped installer")
    out_dir = os.path.join(base, "dist")
    r = subprocess.run([PS, "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", os.path.join(TOOLS, "make_release.ps1"),
                        "-OutDir", out_dir], capture_output=True, text=True, timeout=120)
    eq(r.returncode, 0, "make_release exit code (%s)" % (r.stdout + r.stderr)[-400:])
    zpath = os.path.join(out_dir, "GoblinLedger.zip")
    check(os.path.isfile(zpath), "GoblinLedger.zip built")
    if not os.path.isfile(zpath):
        return
    want = sorted(["GoblinLedger/" + f for f in os.listdir(ADDON) if f != "Data.lua"] +
                  ["Install-Goblin-Ledger.bat", "Uninstall-Goblin-Ledger.bat", "README.txt",
                   "scripts/install.ps1", "scripts/uninstall.ps1", "scripts/common.ps1", "scripts/update_prices.ps1"])
    with zipfile.ZipFile(zpath) as z:
        names = sorted(z.namelist())
        eq(names, want, "zip listing")
        check(not any(n.endswith("Data.lua") for n in names), "no Data.lua in the zip")
        for n in names:
            data = z.read(n)
            check(all(b < 128 for b in data), n + " is plain ASCII")
            check(data.count(b"\n") == data.count(b"\r\n"), n + " has Windows line endings only")
        unz = os.path.join(base, "Downloads", "GoblinLedger")
        z.extractall(unz)
    readme = read(os.path.join(unz, "README.txt"), "r")
    for s in ("Install-Goblin-Ledger.bat", "Uninstall-Goblin-Ledger.bat", "/gl help", "every 30 minutes", "_forever_"):
        check(s in readme, "README.txt mentions %s" % s)
    # Double-clicking the unzipped Install-Goblin-Ledger.bat (pause gets an empty stdin).
    box = Box(base, "unzipped")
    old_install(box)
    env = box.env(search=box.game, answers="y", tasks="ForeverAH Prices")
    env["GOBLINLEDGER_DATA_URL"] = box.prices1
    r = subprocess.run(["cmd.exe", "/c", os.path.join(unz, "Install-Goblin-Ledger.bat")], env=env, capture_output=True,
                       text=True, stdin=subprocess.DEVNULL, timeout=180)
    eq(r.returncode, 0, "unzipped Install-Goblin-Ledger.bat exit code (%s)" % (r.stdout + r.stderr)[-600:])
    addon_files_ok(box, "unzipped bat")
    eq(read(os.path.join(box.dest, "Data.lua")), read(box.prices1), "unzipped bat: prices downloaded")
    check(not os.path.exists(box.old), "unzipped bat: old addon migrated")
    check(any(x.startswith("REGISTER Goblin Ledger Prices") for x in box.tasks()), "unzipped bat: task registered")
    # The unzipped folder can be deleted: the task's updater lives in LOCALAPPDATA.
    shutil.rmtree(os.path.join(base, "Downloads"))
    code, out = run_ps(os.path.join(box.app, "update_prices.ps1"), ["-DataUrl", box.prices2, "-Quiet"], box.env())
    eq(code, 0, "after deleting the unzipped folder, the installed updater still works")
    eq(read(os.path.join(box.dest, "Data.lua")), read(box.prices2), "the installed updater put the new prices in")
    # The owner's collector runs the OLD updater copy in LOCALAPPDATA\ForeverAH with that folder's addon_dir.txt.
    eq(read(os.path.join(box.legacy, "addon_dir.txt"), "r").strip(), box.dest, "collector's old updater now finds GoblinLedger")
    # The new updater copied there by Setup-PC-Collector.bat finds the addon by itself (no -AddonDir).
    shutil.copy(UPDATER, os.path.join(box.legacy, "update_prices_new.ps1"))
    write(box.prices1 + ".newer", price_file(1795007200))
    code, out = run_ps(os.path.join(box.legacy, "update_prices_new.ps1"), ["-DataUrl", box.prices1 + ".newer"], box.env())
    eq(code, 0, "new updater run from LOCALAPPDATA\\ForeverAH finds the addon (%s)" % out[-300:])
    eq(read(os.path.join(box.dest, "Data.lua")), read(box.prices1 + ".newer"), "...and updates GoblinLedger\\Data.lua")
    # Pointer to the old ForeverAH folder only: the updater falls back to the GoblinLedger folder next to it.
    os.remove(os.path.join(box.app, "addon_dir.txt"))
    write(os.path.join(box.legacy, "addon_dir.txt"), box.old + "\r\n")
    write(box.prices1 + ".newest", price_file(1795010800))
    code, out = run_ps(UPDATER, ["-DataUrl", box.prices1 + ".newest"], box.env())
    eq(code, 0, "an old pointer to the ForeverAH folder still finds GoblinLedger (%s)" % out[-300:])
    eq(read(os.path.join(box.dest, "Data.lua")), read(box.prices1 + ".newest"), "...and updates it")


def main():
    if os.name != "nt" or not os.path.isfile(PS):
        print("Windows PowerShell not found: the installer tests need Windows.")
        return 1
    base = tempfile.mkdtemp(prefix="gl_inst_")
    try:
        test_resolve(base)
        box = test_install_migrate(base)
        test_rerun(base, box)
        test_uninstall(base, box)
        test_edge_cases(base)
        test_release(base)
    finally:
        shutil.rmtree(base, ignore_errors=True)
    print()
    if fails:
        print("%d checks passed, %d FAILED" % (passes, len(fails)))
        return 1
    print("ALL PASSED: %d checks" % passes)
    return 0


if __name__ == "__main__":
    sys.exit(main())
