"""Tests for the Goblin Ledger friend installer (tools/goblin-ledger).

Runs install.ps1 and uninstall.ps1 for real, in their test mode, against a
fake game folder in a temporary folder:
  - GOBLINLEDGER_TEST=1: no registry, no real drives, no real scheduled task
    (what would happen to tasks is written to a log file instead)
  - LOCALAPPDATA points into the temporary folder
  - the price "download" is a local file
  - answers to the questions come from GOBLINLEDGER_ANSWERS
Also builds the release zip with make_release.ps1 into the temporary folder
and runs Install-Goblin-Ledger.bat from the unzipped release.

Nothing here touches the real game folder, %LOCALAPPDATA% or Task Scheduler.

    python tools/wow/addon_test/test_installer.py
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
TOOLS = os.path.join(REPO, "tools", "goblin-ledger")
ADDON = os.path.join(REPO, "wow-addon", "GoblinLedger")
UPDATER = os.path.join(REPO, "tools", "wow", "addon", "update_prices.ps1")
PS = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32", "WindowsPowerShell", "v1.0", "powershell.exe")
HEADER = "-- ForeverAH price data. Generated by grantdenney.com/wow. Do not edit."

passes = 0
fails = []


def check(ok, what):
    global passes
    if ok:
        passes += 1
    else:
        fails.append(what)
        print("FAIL: " + what)


def eq(got, want, what):
    check(got == want, "%s: got %r, want %r" % (what, got, want))


def read(p, mode="rb"):
    with open(p, mode) as fh:
        return fh.read()


def peek(p, mode="rb"):
    """read(), or None when the file is not there (the check then fails instead of stopping the run)."""
    return read(p, mode) if os.path.isfile(p) else None


def write(p, data):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "wb") as fh:
        fh.write(data if isinstance(data, bytes) else data.encode("ascii"))


def tree(root):
    """{relative path: sha1} of every file under root."""
    out = {}
    for d, _, files in os.walk(root):
        for f in files:
            p = os.path.join(d, f)
            out[os.path.relpath(p, root)] = hashlib.sha1(read(p)).hexdigest()
    return out


def price_file(stamp):
    lines = [HEADER, "ForeverAH_Data = {", "  v = 3,", "  updated = %d," % stamp, '  region = "us",', "  items = {"]
    for i in range(2589, 2600):
        lines.append('    [%d] = "%s",' % (i, "a,b,c;d,e;1" * 3))
    lines += ["  },", "}"]
    return "\n".join(lines) + "\n"


class Box:
    """A fake PC: game folder, LOCALAPPDATA, the owner's old install."""

    def __init__(self, base, name, games="Games"):
        self.root = os.path.join(base, name)
        self.local = os.path.join(self.root, "local")
        self.wow = os.path.join(self.root, games, "World of Warcraft")
        self.game = os.path.join(self.wow, "_forever_")
        self.addons = os.path.join(self.game, "Interface", "AddOns")
        self.dest = os.path.join(self.addons, "GoblinLedger")
        self.old = os.path.join(self.addons, "ForeverAH")
        self.app = os.path.join(self.local, "GoblinLedger")
        self.legacy = os.path.join(self.local, "ForeverAH")
        self.tasklog = os.path.join(self.root, "tasks.log")
        self.prices1 = os.path.join(self.root, "prices1.lua")
        self.prices2 = os.path.join(self.root, "prices2.lua")
        os.makedirs(self.local)
        write(os.path.join(self.game, "Wow.exe"), b"MZ")
        write(os.path.join(self.addons, "Questie", "Questie.toc"), "## Title: Questie\n")
        write(self.prices1, price_file(1795000000))
        write(self.prices2, price_file(1795003600))

    def sv(self, acct, name):
        return os.path.join(self.game, "WTF", "Account", acct, "SavedVariables", name)

    def env(self, answers=None, search=None, tasks="", wow_running=0):
        e = dict(os.environ)
        e.update({"GOBLINLEDGER_TEST": "1", "LOCALAPPDATA": self.local, "GOBLINLEDGER_TASKLOG": self.tasklog,
                  "GOBLINLEDGER_TEST_TASKS": tasks, "GOBLINLEDGER_TEST_WOW": str(wow_running),
                  "GOBLINLEDGER_SEARCH": search if search is not None else os.path.join(self.root, "nowhere", "_forever_")})
        e.pop("GOBLINLEDGER_ANSWERS", None)
        e.pop("GOBLINLEDGER_DATA_URL", None)
        if answers is not None:
            e["GOBLINLEDGER_ANSWERS"] = answers
        return e

    def tasks(self):
        return read(self.tasklog, "r").splitlines() if os.path.exists(self.tasklog) else []

    def clear_tasks(self):
        if os.path.exists(self.tasklog):
            os.remove(self.tasklog)


def run_ps(script, args, env):
    r = subprocess.run([PS, "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", script] + args,
                       env=env, capture_output=True, text=True, errors="replace", stdin=subprocess.DEVNULL, timeout=180)
    return r.returncode, r.stdout + r.stderr


def run_bat(bat, env):
    """A double-click in Explorer: cmd runs the .bat from its own folder."""
    r = subprocess.run(["cmd.exe", "/c", bat], env=env, cwd=os.path.dirname(bat), capture_output=True, text=True,
                       errors="replace", stdin=subprocess.DEVNULL, timeout=180)
    return r.returncode, r.stdout + r.stderr


def install(box, args=(), **kw):
    return run_ps(os.path.join(TOOLS, "install.ps1"), list(args), box.env(**kw))


def uninstall(box, args=(), **kw):
    return run_ps(os.path.join(TOOLS, "uninstall.ps1"), list(args), box.env(**kw))


def addon_files_ok(box, label):
    src = tree(ADDON)
    src.pop("Data.lua", None)
    got = tree(box.dest)
    got.pop("Data.lua", None)
    eq(got, src, label + ": the addon files are exactly the release's")


