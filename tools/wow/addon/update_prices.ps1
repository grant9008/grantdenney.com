<#
  Goblin Ledger price updater (the addon was called Forever AH before).

  WoW addons cannot use the internet, so this downloads the newest price file
  (built every hour from Blizzard's auction house data) and saves it as
  Data.lua in the Goblin Ledger addon folder. The game reads it when you log
  in or type /reload.

  Usually started by Install-Goblin-Ledger.bat, Update-WoW-Prices.bat, the
  "Goblin Ledger Prices" scheduled task (every 30 minutes) or the owner's
  price collector. You never need to run it by hand.

    -AddonDir  the GoblinLedger addon folder. Default: the path the installer
               saved in %LOCALAPPDATA%\GoblinLedger\addon_dir.txt (or, from an
               install made before the rename, %LOCALAPPDATA%\ForeverAH\addon_dir.txt)
    -DataUrl   where to get the price file. An https:// address, or a file
               path (used for testing)
    -Quiet     print nothing (the scheduled task uses this). Every run still
               writes one line to %LOCALAPPDATA%\GoblinLedger\update.log

  This script keeps its notes in %LOCALAPPDATA%\GoblinLedger wherever it is
  started from, so every copy (the installed one, the collector's) shares them.

  Downloads are small when nothing changed: the server's ETag for the file
  that is installed is kept in %LOCALAPPDATA%\GoblinLedger\etag.txt and sent
  back, so an unchanged file is not downloaded again. The file comes gzip
  compressed when the server offers it.

  The price file keeps its old name (ForeverAH_Data.lua) and first line, so
  copies of this updater from before the rename still accept it.

  Exit codes: 0 updated or already up to date, 2 addon not installed,
  3 prices not published yet, 4 bad or missing file, 5 no connection,
  6 could not save.
#>
param(
    [string]$AddonDir,
    [string]$DataUrl = 'https://raw.githubusercontent.com/grant9008/grantdenney.com/wow-data/ForeverAH_Data.lua',
    [switch]$Quiet
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'   # the progress bar makes downloads very slow in Windows PowerShell

# The first line of every price file (fetch_ah.py writes it; it is not shown in game).
$Header = '-- ForeverAH price data. Generated by grantdenney.com/wow. Do not edit.'
$AppDir = Join-Path $env:LOCALAPPDATA 'GoblinLedger'
$LegacyDir = Join-Path $env:LOCALAPPDATA 'ForeverAH'   # installs from before the rename
$LogFile = Join-Path $AppDir 'update.log'
$EtagFile = Join-Path $AppDir 'etag.txt'
$script:TmpFile = $null
$script:Etag = $null

function Say([string]$text) {
    if (-not $Quiet) { Write-Host "  $text" }
}

function Write-Log([string]$status, [string]$text) {
    try {
        if (-not (Test-Path -LiteralPath $AppDir)) { New-Item -ItemType Directory -Path $AppDir -Force | Out-Null }
        $line = '{0}  {1,-5}  {2}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $status, $text
        $lines = @()
        if (Test-Path -LiteralPath $LogFile) { $lines = @(Get-Content -LiteralPath $LogFile -Encoding UTF8) }
        $lines = @($lines + $line)
        if ($lines.Count -gt 200) { $lines = $lines[($lines.Count - 200)..($lines.Count - 1)] }
        Set-Content -LiteralPath $LogFile -Value $lines -Encoding UTF8
    } catch { }   # a log problem must never stop the update
}

function Finish([int]$code, [string]$status, [string]$logText, [string[]]$userLines) {
    if ($script:TmpFile) { Remove-Item -LiteralPath $script:TmpFile -Force -ErrorAction SilentlyContinue }
    foreach ($l in $userLines) { Say $l }
    Write-Log $status $logText
    exit $code
}

function Get-Stamp([string]$path) {
    # The "updated = <unix seconds>" stamp is near the top, so only the first 4 KB are read.
    try {
        $fs = [IO.File]::OpenRead($path)
        try {
            $buf = New-Object byte[] 4096
            $n = $fs.Read($buf, 0, $buf.Length)
        } finally { $fs.Dispose() }
        $m = [regex]::Match([Text.Encoding]::UTF8.GetString($buf, 0, $n), '\bupdated\s*=\s*(\d+)')
        if ($m.Success) { return [int64]$m.Groups[1].Value }
    } catch { }
    return [int64]0
}

function Format-Stamp([int64]$stamp) {
    $when = [DateTimeOffset]::FromUnixTimeSeconds($stamp).LocalDateTime
    $mins = [int]((Get-Date) - $when).TotalMinutes
    if ($mins -lt 1) { $ago = 'just now' }
    elseif ($mins -lt 120) { $ago = "$mins minutes ago" }
    elseif ($mins -lt 2880) { $ago = '{0} hours ago' -f [int]($mins / 60) }
    else { $ago = '{0} days ago' -f [int]($mins / 1440) }
    return '{0} ({1})' -f $when.ToString('ddd d MMM, h:mm tt'), $ago
}

function Test-AccessDenied($err) {
    $e = $err.Exception
    while ($e) {
        if ($e -is [UnauthorizedAccessException]) { return $true }
        $e = $e.InnerException
    }
    return ($err.CategoryInfo.Category -eq 'PermissionDenied') -or ($err.Exception.Message -match 'denied')
}

function Get-WebException($err) {
    $e = $err.Exception
    while ($e) {
        if ($e -is [Net.WebException]) { return $e }
        $e = $e.InnerException
    }
    return $null
}

# The saved ETag counts only for this address and for the Data.lua installed now.
function Read-Etag([string]$url, [int64]$installed) {
    try {
        if ($installed -le 0 -or -not (Test-Path -LiteralPath $EtagFile)) { return $null }
        $l = @(Get-Content -LiteralPath $EtagFile -Encoding UTF8)
        if ($l.Count -ge 3 -and $l[0] -eq $url -and $l[2] -eq [string]$installed -and $l[1]) { return [string]$l[1] }
    } catch { }
    return $null
}

function Save-Etag([string]$url, [string]$etag, [int64]$stamp) {
    try {
        if (-not $etag) {
            Remove-Item -LiteralPath $EtagFile -Force -ErrorAction SilentlyContinue
            return
        }
        if (-not (Test-Path -LiteralPath $AppDir)) { New-Item -ItemType Directory -Path $AppDir -Force | Out-Null }
        Set-Content -LiteralPath $EtagFile -Value @($url, $etag, [string]$stamp) -Encoding UTF8
    } catch { }
}

$AccessHelp = @(
    'Windows does not let normal programs save into the game folder on this PC.',
    'Fix it once: right-click Install-Goblin-Ledger.bat and choose "Run as administrator".',
    'That gives this PC permission to save price updates into the GoblinLedger folder',
    '(only that folder), so updates work from then on. Your current prices were kept.'
)

# 1. Where the addon is ---------------------------------------------------------
if (-not $AddonDir) {
    foreach ($dir in @($AppDir, $LegacyDir)) {
        $saved = Join-Path $dir 'addon_dir.txt'
        if (Test-Path -LiteralPath $saved) {
            $AddonDir = [string](Get-Content -LiteralPath $saved -TotalCount 1)
            if ($AddonDir -and $AddonDir.Trim()) { break }
        }
    }
}
if ($AddonDir) { $AddonDir = $AddonDir.Trim().Trim('"').TrimEnd('\') }
# An old saved path to the ForeverAH folder: the addon is GoblinLedger now.
if ($AddonDir -and -not (Test-Path -LiteralPath $AddonDir -PathType Container) -and
        (Split-Path -Leaf $AddonDir) -eq 'ForeverAH') {
    $renamed = Join-Path (Split-Path -Parent $AddonDir) 'GoblinLedger'
    if (Test-Path -LiteralPath $renamed -PathType Container) { $AddonDir = $renamed }
}
if (-not $AddonDir) {
    Finish 2 'ERROR' 'no addon folder saved (not installed)' @(
        'Goblin Ledger is not installed yet.',
        'Double-click Install-Goblin-Ledger.bat first.')
}
if (-not (Test-Path -LiteralPath $AddonDir -PathType Container)) {
    Finish 2 'ERROR' "addon folder missing: $AddonDir" @(
        'The Goblin Ledger addon folder is missing:',
        "    $AddonDir",
        'Double-click Install-Goblin-Ledger.bat to put it back.')
}
$Dest = Join-Path $AddonDir 'Data.lua'
$oldStamp = [int64]0
if (Test-Path -LiteralPath $Dest) { $oldStamp = Get-Stamp $Dest }

# 2. Download to a temp file ----------------------------------------------------
try {
    [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
} catch { }
$script:TmpFile = Join-Path ([IO.Path]::GetTempPath()) ('GoblinLedger_' + [guid]::NewGuid().ToString('N') + '.lua')
$isWeb = $DataUrl -match '^(?i)https?://'
try {
    if ($isWeb) {
        $req = [Net.HttpWebRequest]::Create($DataUrl)
        $req.UserAgent = 'GoblinLedger-price-updater'
        $req.AutomaticDecompression = [Net.DecompressionMethods]::GZip -bor [Net.DecompressionMethods]::Deflate
        $req.Timeout = 60000            # to connect and get an answer
        $req.ReadWriteTimeout = 60000   # for each read: a slow line is fine while the data keeps coming
        $known = Read-Etag $DataUrl $oldStamp
        if ($known) { $req.Headers.Add('If-None-Match', $known) }
        $resp = $null
        try {
            $resp = $req.GetResponse()
        } catch {
            $we = Get-WebException $_
            if ($we -and $we.Response -and [int]$we.Response.StatusCode -eq 304) {
                Finish 0 'SKIP' 'not changed on the server' @(
                    'Prices are already up to date.',
                    ('Snapshot from {0}.' -f (Format-Stamp $oldStamp)))
            }
            throw
        }
        try {
            $script:Etag = $resp.Headers.Get('ETag')
            $in = $resp.GetResponseStream()
            $out = [IO.File]::Create($script:TmpFile)
            try { $in.CopyTo($out) } finally { $out.Dispose(); $in.Dispose() }
        } finally { $resp.Close() }
    } else {
        $src = $DataUrl
        if ($src -match '^(?i)file:') { $src = ([Uri]$src).LocalPath }
        if (-not (Test-Path -LiteralPath $src -PathType Leaf)) {
            Finish 4 'ERROR' "price file not found: $src" @(
                'The price file was not found:',
                "    $src")
        }
        Copy-Item -LiteralPath $src -Destination $script:TmpFile -Force
    }
} catch {
    $err = $_
    $status = $null
    $we = Get-WebException $err
    try { if ($we -and $we.Response) { $status = [int]$we.Response.StatusCode } } catch { }
    if ($status -eq 404) {
        Finish 3 'WAIT' "404 not published yet: $DataUrl" @(
            'Prices are not published yet, so there was nothing to download.',
            'Nothing was changed. Try again later.')
    }
    if ($status) {
        Finish 5 'ERROR' "HTTP $status from $DataUrl" @(
            "GitHub answered with error $status. It is usually a short hiccup:",
            'try again in a few minutes. Your current prices were kept.')
    }
    if (-not $isWeb -and (Test-AccessDenied $err)) {
        Finish 4 'ERROR' "cannot read $DataUrl : $($err.Exception.Message)" @(
            'Windows did not allow reading the price file. Your current prices were kept.')
    }
    if ($isWeb -and $we -and $we.Status -eq [Net.WebExceptionStatus]::Timeout) {
        Finish 5 'ERROR' "timed out: $($err.Exception.Message)" @(
            'The download stopped answering, so it was given up.',
            'The internet connection may be slow right now: try again later.',
            'Your current prices were kept.')
    }
    if ($isWeb) {
        Finish 5 'ERROR' "no connection: $($err.Exception.Message)" @(
            'Could not reach GitHub to download the prices.',
            'Check that this PC is connected to the internet, then try again.',
            'Your current prices were kept.')
    }
    Finish 4 'ERROR' "copy failed: $($err.Exception.Message)" @(
        'Could not read the price file. Your current prices were kept.',
        "    $($err.Exception.Message)")
}

# 3. Check it is a complete Goblin Ledger price file ----------------------------
$size = (Get-Item -LiteralPath $script:TmpFile).Length
$problem = $null
$newStamp = [int64]0
$itemCount = 0
if ($size -le 100) {
    $problem = "file too small ($size bytes)"
} else {
    $text = [IO.File]::ReadAllText($script:TmpFile, [Text.Encoding]::UTF8)
    $nl = $text.IndexOf("`n")
    $first = if ($nl -ge 0) { $text.Substring(0, $nl).TrimEnd("`r") } else { $text }
    if ($first -ne $Header) {
        $problem = 'first line is not the price file header'
    } elseif ($text.IndexOf('ForeverAH_Data = {') -lt 0) {
        $problem = 'no ForeverAH_Data table'
    } elseif (-not $text.TrimEnd().EndsWith('}')) {
        $problem = 'file is cut off'
    } else {
        $m = [regex]::Match($text, '(?m)^\s*updated\s*=\s*(\d+)\s*,')
        if ($m.Success) { $newStamp = [int64]$m.Groups[1].Value }
        if ($newStamp -le 0) { $problem = 'no "updated" stamp' }
        $itemCount = [regex]::Matches($text, '(?m)^\s*\[\d+\]\s*=\s*"').Count
    }
    $text = $null
}
if ($problem) {
    Finish 4 'ERROR' "rejected download ($problem) from $DataUrl" @(
        'The downloaded price file did not look right, so it was not used.',
        'Your current prices were kept. Try again in a few minutes.')
}

# 4. Only replace when it is newer than what is installed -----------------------
if ($newStamp -le $oldStamp) {
    # Same file as installed: remember its ETag so next time nothing is downloaded.
    if ($isWeb -and $newStamp -eq $oldStamp) { Save-Etag $DataUrl $script:Etag $newStamp }
    Finish 0 'SKIP' "already current (snapshot $newStamp)" @(
        'Prices are already up to date.',
        ('Snapshot from {0}.' -f (Format-Stamp $oldStamp)))
}

# 5. Save as Data.lua (Data.lua.new first, then swapped in) ---------------------
$newFile = Join-Path $AddonDir 'Data.lua.new'
try {
    Copy-Item -LiteralPath $script:TmpFile -Destination $newFile -Force
    Move-Item -LiteralPath $newFile -Destination $Dest -Force
} catch {
    $err = $_
    Remove-Item -LiteralPath $newFile -Force -ErrorAction SilentlyContinue
    if (Test-AccessDenied $err) {
        Finish 6 'ERROR' "access denied writing $Dest" $AccessHelp
    }
    Finish 6 'ERROR' "could not save $Dest : $($err.Exception.Message)" @(
        'Could not save the new prices into the addon folder:',
        "    $($err.Exception.Message)",
        'Your current prices were kept. Close anything that has Data.lua open and try again.')
}

if ($isWeb) { Save-Etag $DataUrl $script:Etag $newStamp } else { Save-Etag '' '' 0 }
$kb = [math]::Round($size / 1KB)
Finish 0 'OK' ("updated to snapshot $newStamp, $itemCount items, $kb KB") @(
    ('Prices updated: {0} items, snapshot from {1}.' -f $itemCount, (Format-Stamp $newStamp)))
