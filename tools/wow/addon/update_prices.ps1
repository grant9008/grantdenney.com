# One line in update.log (or $file), which keeps its last 200 lines.
function Write-Log([string]$status, [string]$text, [string]$file = $LogFile) {
    try {
        if (-not (Test-Path -LiteralPath $AppDir)) { New-Item -ItemType Directory -Path $AppDir -Force | Out-Null }
        $line = '{0}  {1,-5}  {2}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $status, $text
        $lines = @()
        if (Test-Path -LiteralPath $file) { $lines = @(Get-Content -LiteralPath $file -Encoding UTF8) }
        $lines = @($lines + $line)
        if ($lines.Count -gt 200) { $lines = $lines[($lines.Count - 200)..($lines.Count - 1)] }
        Set-Content -LiteralPath $file -Value $lines -Encoding UTF8
    } catch { }   # a log problem must never stop the update
}

function Finish([int]$code, [string]$status, [string]$logText, [string[]]$userLines) {
    if ($script:TmpFile) { Remove-Item -LiteralPath $script:TmpFile -Force -ErrorAction SilentlyContinue }
    foreach ($l in $userLines) { Say $l }
    Write-Log $status $logText
    exit $code
}

function Get-Stamp([string]$path) {
    # The "updated = <unix seconds>" stamp is near the top, so only the first 4 KB are read.
    try {
        $fs = [IO.File]::OpenRead($path)
        try {
            $buf = New-Object byte[] 4096
            $n = $fs.Read($buf, 0, $buf.Length)
        } finally { $fs.Dispose() }
        $m = [regex]::Match([Text.Encoding]::UTF8.GetString($buf, 0, $n), '\bupdated\s*=\s*(\d+)')
        if ($m.Success) { return [int64]$m.Groups[1].Value }
    } catch { }
    return [int64]0
}

function Format-Stamp([int64]$stamp) {
    $when = [DateTimeOffset]::FromUnixTimeSeconds($stamp).LocalDateTime
    $mins = [int]((Get-Date) - $when).TotalMinutes
    if ($mins -lt 1) { $ago = 'just now' }
    elseif ($mins -lt 120) { $ago = "$mins minutes ago" }
    elseif ($mins -lt 2880) { $ago = '{0} hours ago' -f [int]($mins / 60) }
    else { $ago = '{0} days ago' -f [int]($mins / 1440) }
    return '{0} ({1})' -f $when.ToString('ddd d MMM, h:mm tt'), $ago
}

function Test-AccessDenied($err) {
    $e = $err.Exception
    while ($e) {
        if ($e -is [UnauthorizedAccessException]) { return $true }
        $e = $e.InnerException
    }
    return ($err.CategoryInfo.Category -eq 'PermissionDenied') -or ($err.Exception.Message -match 'denied')
}

function Get-WebException($err) {
    $e = $err.Exception
    while ($e) {
        if ($e -is [Net.WebException]) { return $e }
        $e = $e.InnerException
    }
    return $null
}

# The saved ETag counts only for this address and for the Data.lua installed now.
function Read-Etag([string]$url, [int64]$installed) {
    try {
        if ($installed -le 0 -or -not (Test-Path -LiteralPath $EtagFile)) { return $null }
        $l = @(Get-Content -LiteralPath $EtagFile -Encoding UTF8)
        if ($l.Count -ge 3 -and $l[0] -eq $url -and $l[2] -eq [string]$installed -and $l[1]) { return [string]$l[1] }
    } catch { }
    return $null
}

function Save-Etag([string]$url, [string]$etag, [int64]$stamp) {
    try {
        if (-not $etag) {
            Remove-Item -LiteralPath $EtagFile -Force -ErrorAction SilentlyContinue
            return
