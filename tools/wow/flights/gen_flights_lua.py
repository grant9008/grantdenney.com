"""Write the flight data block of wow-addon/GoblinLedger/Flights.lua (between -- BEGIN DATA and -- END DATA).

    python -I tools/wow/flights/build_taxi.py <csv dir> taxi.json      # first: Forever's tables -> taxi.json
    python -I tools/wow/flights/gen_flights_lua.py taxi.json           # rewrite the block
    python -I tools/wow/flights/gen_flights_lua.py taxi.json --check   # exit 1 when the block is out of date

Input: taxi.json from build_taxi.py, built from WoW Forever's own client tables for build 1.60.1.70959 on
wago.tools (TaxiNodes, TaxiPath, TaxiPathNode, UiMapAssignment; build_taxi.py says where and how).
The fields used here:
    nodes[id]:   name, kind ("flight" only), world [x, y, z] (the frame UnitPosition("player") uses: its first
                 two returns), taxiXY [x, y] (0..1 from the top left, like TaxiNodePosition)
    edges[]:     path, from, to, seconds, points [[x, y, z, seconds from take-off], ...], special (optional)
    junctions:   {"a>b>c": seconds saved at b when the flight goes on past it}
Each edge's seconds = 0.56 + L / 30.32 + stop delays, L the length of a uniform Catmull-Rom spline
through the path's points. 30.32 yd/s is the taxi speed (434% of run speed). Against the 2010
(pre-Cataclysm) warcraft.wiki.gg flight times, timed by players: over all 257, median error 1.2 s, mean
3.3 s, 86% within 6 s, 93% within 10 s; Alliance's 121: median 1.1 s, mean 2.2 s, 92% within 6 s. No
other addon's flight times are used. A special edge (its path changes maps: Alterac Valley's) gets no time.

Output (Lua, plain ASCII, CRLF like the other addon files):
    NODES[id]       = { name, world x, world y, taxi map x, taxi map y }
    EDGES["a>b"]    = seconds at normal taxi speed, take-off to landing
    JUNC["a>b>c"]   = seconds saved at b, flying a>b>c without landing at b (the shortened join)
    TRACKS["a>b"]   = "x,y;x,y;..." world x, y every TRACK_STEP seconds from take-off, the last pair the
                      landing spot
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
TARGET = os.path.join(ROOT, "wow-addon", "GoblinLedger", "Flights.lua")
BEGIN, END = "-- BEGIN DATA", "-- END DATA"
TRACK_STEP = 20   # seconds between two track points (Flights.lua's TRACK_STEP must match)


def lua_str(s):
    s = str(s)
    if any(ord(c) > 126 or ord(c) < 32 for c in s):
        raise SystemExit("not plain ASCII: %r" % s)
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(v, nd):
    t = ("%." + str(nd) + "f") % v
    if "." in t:
        t = t.rstrip("0").rstrip(".")
    return "0" if t in ("-0", "") else t


def track(points, seconds):
    """World x, y at 0, STEP, 2*STEP, ... seconds from take-off (linear between the path points), then the
    landing spot."""
    out, k = [], 0
    j = 0
    while k * TRACK_STEP < seconds - TRACK_STEP / 2:
        t = k * TRACK_STEP
        while j + 1 < len(points) and points[j + 1][3] < t:
            j += 1
        a = points[j]
        b = points[j + 1] if j + 1 < len(points) else a
        span = b[3] - a[3]
        f = 0.0 if span <= 0 else max(0.0, min(1.0, (t - a[3]) / span))
        out.append((a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f))
        k += 1
    last = points[-1]
    out.append((last[0], last[1]))
    return ";".join("%d,%d" % (round(x), round(y)) for x, y in out)


def build(taxi):
    nodes = {int(k): v for k, v in taxi["nodes"].items() if v.get("kind") == "flight"}
    edges = {}
    if "junctions" not in taxi:
        raise SystemExit("taxi.json has no junctions: build it again with tools/wow/flights/build_taxi.py")
    for e in sorted(taxi["edges"], key=lambda e: e["path"]):
        a, b = int(e["from"]), int(e["to"])
        if a not in nodes or b not in nodes or a == b or e.get("special"):
            continue
        key = "%d>%d" % (a, b)
        if key in edges:   # the same flight twice (two path ids, same points): the first one
            continue
        edges[key] = e
    used = sorted({int(k.split(">")[0]) for k in edges} | {int(k.split(">")[1]) for k in edges})

    def order(k):
        a, b = k.split(">")
        return int(a), int(b)

    lines = [BEGIN,
             "-- Generated by tools/wow/flights/gen_flights_lua.py from Forever's own taxi tables (build 1.60.1.70959,",
             "-- wago.tools TaxiNodes, TaxiPath, TaxiPathNode, UiMap, UiMapAssignment). Do not edit by hand.",
             "-- A flight's time = 0.56 + its spline length / 30.32 yd/s (434% of run speed) + stops. Against 257",
             "-- pre-Cataclysm wiki flight times (timed by players): median error 1.2 s, mean 3.3 s, 86% within 6 s,",
             "-- 93% within 10 s (Alliance's 121: median 1.1 s, mean 2.2 s, 92% within 6 s). Alterac Valley's flights",
             "-- change maps: they have no time here.",
             "-- NODES[id] = { name, world x, world y, taxi map x, taxi map y } (x, y as UnitPosition(\"player\") gives them)",
             "local NODES = {"]
    for i in used:
        n = nodes[i]
        wx, wy = n["world"][0], n["world"][1]
        txy = n.get("taxiXY")
        tail = (", %s, %s" % (num(txy[0], 4), num(txy[1], 4))) if txy else ""
        lines.append("  [%d] = { %s, %d, %d%s }," % (i, lua_str(n["name"]), round(wx), round(wy), tail))
    lines.append("}")
    lines.append("-- EDGES[\"from>to\"] = seconds from take-off to landing at normal taxi speed (one hop)")
    lines.append("local EDGES = {")
    row = []
    for k in sorted(edges, key=order):
        row.append("[%s] = %s," % (lua_str(k), num(edges[k]["seconds"], 1)))
        if len(row) == 6:
            lines.append("  " + " ".join(row))
            row = []
    if row:
        lines.append("  " + " ".join(row))
    lines.append("}")
    junc = {k: v for k, v in taxi["junctions"].items()
            if all("%s>%s" % p in edges for p in zip(k.split(">"), k.split(">")[1:]))}
    lines.append("-- JUNC[\"a>b>c\"] = seconds saved at b when the flight goes on past it without landing: the game")
    lines.append("-- joins the two paths and cuts the corner (TrinityCore's FlightPathMovementGenerator::LoadPath)")
    lines.append("local JUNC = {")
    row = []
    for k in sorted(junc, key=lambda k: tuple(int(x) for x in k.split(">"))):
        row.append("[%s] = %s," % (lua_str(k), num(junc[k], 1)))
        if len(row) == 6:
            lines.append("  " + " ".join(row))
            row = []
    if row:
        lines.append("  " + " ".join(row))
    lines.append("}")
    lines.append("-- TRACKS[\"from>to\"] = world x,y every %d s from take-off; the last pair is the landing spot" % TRACK_STEP)
    lines.append("local TRACKS = {")
    for k in sorted(edges, key=order):
        e = edges[k]
        lines.append("  [%s] = %s," % (lua_str(k), lua_str(track(e["points"], e["seconds"]))))
    lines.append("}")
    lines.append(END)
    return lines, len(used), len(edges), len(junc)


def main(argv):
    if not argv or argv[0].startswith("-"):
        print(__doc__)
        return 2
    taxi = json.load(open(argv[0], encoding="utf-8"))
    check = "--check" in argv[1:]
    lines, n_nodes, n_edges, n_junc = build(taxi)
    raw = open(TARGET, "rb").read().decode("ascii")
    eol = "\r\n" if "\r\n" in raw else "\n"
    text = raw.replace("\r\n", "\n")
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < i:
        raise SystemExit("no %s ... %s block in %s" % (BEGIN, END, TARGET))
    j = text.find("\n", j)
    j = len(text) if j < 0 else j
    new = text[:i] + "\n".join(lines) + text[j:]
    if check:
        same = new == text
        print("Flights.lua data is %s (%d nodes, %d flights, %d junctions)" % ("up to date" if same else "OUT OF DATE",
                                                                             n_nodes, n_edges, n_junc))
        return 0 if same else 1
    open(TARGET, "wb").write(new.replace("\n", eol).encode("ascii"))
    print("wrote %s: %d nodes, %d flights, %d junctions" % (TARGET, n_nodes, n_edges, n_junc))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
